'use strict';

// 078 B.2 (IC-003): the rule compiler and the committed hook table it generates.

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { tempDir } = require('../helper/tmp');
const { EMISSION_RULES, INPUT_DOMAINS, arbitrate } = require('../../src/runtime/context/arbitrate.ts');
const { TABLE_REL, compileArms, compileEmissionTable } = require('../../src/runtime/context/emission-rules.ts');

const REPO = path.resolve(__dirname, '../..');
const GENERATOR_REL = 'src/runtime/context/emission-rules.ts';
const TABLE = path.join(REPO, TABLE_REL);
const BASH = '/bin/bash';
const SILENCE_TOKENS = ['context-pack', 'delivery/', 'omissions', 'packEnd', '[end of pack]'];

function runGenerator(root, ...args) {
  return spawnSync(process.execPath, [path.join(root, GENERATOR_REL), ...args], { cwd: root, encoding: 'utf8' });
}

/** A minimal copy of the generator, its imports and the committed table, so a test can edit either side. */
function sandbox(t) {
  const root = tempDir(t, 'doflow-emission-rules-');
  for (const rel of ['src/helper/repo-root.ts', 'src/runtime/context/arbitrate.ts', 'src/runtime/context/identity.ts', GENERATOR_REL, TABLE_REL]) {
    fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
    fs.copyFileSync(path.join(REPO, rel), path.join(root, rel));
  }
  return root;
}

function stateFor(names, values) {
  const request = {
    identity: { role: 'main', lineageKind: 'default-main' },
    state: {
      bootstrapped: false, subagent: false, ownSummary: 'none', legacy: false,
      grant: 'none', refusedSeen: false, warning: false, nudge: 'none',
    },
    budget: { maxBytes: 16384, source: 'default' },
  };
  names.forEach((name, i) => {
    const raw = values[i];
    const value = raw === 'true' ? true : raw === 'false' ? false : raw;
    if (name === 'role' || name === 'lineageKind') request.identity[name] = value;
    else request.state[name] = value;
  });
  return request;
}

test('IC-003 --check is 0 on the committed table, and the table is the compiled text', () => {
  const result = runGenerator(REPO, '--check');
  assert.equal(result.status, 0, result.stderr);
  assert.equal(fs.readFileSync(TABLE, 'utf8'), compileEmissionTable());
});

test('IC-003 --check is 1 after a one-byte edit of the table', (t) => {
  const root = sandbox(t);
  const table = path.join(root, TABLE_REL);
  const text = fs.readFileSync(table, 'utf8');
  fs.writeFileSync(table, text.replace('DF_ACTION=whole', 'DF_ACTION=whale'));
  assert.equal(runGenerator(root, '--check').status, 1);
  assert.equal(runGenerator(root, '--write').status, 0);
  assert.equal(runGenerator(root, '--check').status, 0);
  assert.equal(fs.readFileSync(table, 'utf8'), text);
});

test('IC-003 negative control: a rule added without regenerating fails --check', (t) => {
  const root = sandbox(t);
  const rules = path.join(root, 'src/runtime/context/arbitrate.ts');
  const source = fs.readFileSync(rules, 'utf8');
  const anchor = "  rule('delta', 'pack', ['bootstrapped'], 'per-item', [";
  assert.ok(source.includes(anchor));
  fs.writeFileSync(rules, source.replace(anchor,
    `  rule('delta', 'slot', ['bootstrapped'], 'n/a', [\n    { when: [['true']], action: 'claim' },\n  ]),\n${anchor}`));
  const result = runGenerator(root, '--check');
  assert.equal(result.status, 1);
  assert.match(result.stderr, /stale/);
});

test('IC-003 usage errors exit 2', () => {
  for (const args of [[], ['--bogus'], ['--write', '--check']]) {
    const result = runGenerator(REPO, ...args);
    assert.equal(result.status, 2, `args ${JSON.stringify(args)}`);
    assert.match(result.stderr, /usage:/);
  }
});

test('IC-003 format: header, four variables, sorted explicit arms, skip fallback, no glob, no silence token', () => {
  const text = fs.readFileSync(TABLE, 'utf8');
  const lines = text.split('\n');
  assert.equal(lines[0], '# Generated by node src/runtime/context/emission-rules.ts --write. Do not edit.');
  assert.match(lines[1], /^# rules-digest: sha256:[0-9a-f]{64}$/);
  assert.deepEqual(lines.slice(2, 6), [
    'DF_RULES_VERSION=1', 'DF_RULES_MAX_BYTES_DEFAULT=16384', 'DF_RULES_SUMMARY_CAP=4000', 'DF_RULES_SUMMARY_READ=65536',
  ]);
  const arms = lines.filter((l) => /^    '/.test(l));
  const keys = arms.map((l) => l.match(/^    '([^']+)'\) DF_ACTION=[a-z]+ ;;$/)[1]);
  const compiled = compileArms();
  assert.equal(arms.length, compiled.length);
  assert.deepEqual(keys, compiled.map((a) => `${a.event}.${a.segment}|${a.vector}`));
  const sortKey = (k) => { const [es, v] = k.split('|'); const dot = es.indexOf('.'); return [es.slice(0, dot), es.slice(dot + 1), v]; };
  for (let i = 1; i < keys.length; i += 1) {
    const [a, b] = [sortKey(keys[i - 1]), sortKey(keys[i])];
    const order = a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : a[1] < b[1] ? -1 : a[1] > b[1] ? 1 : a[2] < b[2] ? -1 : 1;
    assert.equal(order, -1, `${keys[i - 1]} before ${keys[i]}`);
  }
  for (const key of keys) assert.doesNotMatch(key, /[*?[\]]/);
  assert.equal(lines.filter((l) => l.includes('*) DF_ACTION=skip ;;')).length, 1);
  for (const token of SILENCE_TOKENS) assert.ok(!text.includes(token), `contains ${token}`);
});

test('IC-003 every arm, and every skip, equals arbitrate() for that vector', () => {
  const armed = new Map(compileArms().map((a) => [`${a.event}.${a.segment}|${a.vector}`, a.action]));
  let checked = 0;
  for (const r of EMISSION_RULES) {
    let combos = [[]];
    for (const name of r.inputs) combos = combos.flatMap((p) => INPUT_DOMAINS[name].map((v) => [...p, v]));
    for (const values of combos) {
      const decision = arbitrate({ ...stateFor(r.inputs, values), event: r.event });
      const key = `${r.event}.${r.segment}|${values.join(':')}`;
      assert.equal(armed.get(key) ?? 'skip', decision.actions[r.segment], key);
      checked += 1;
    }
  }
  assert.ok(checked > armed.size);
});

test('IC-003 sourcing under /bin/bash with set -euo pipefail defines one function and four variables, prints nothing', (t) => {
  const script = [
    'set -euo pipefail',
    'before_f=$(declare -F | sort); before_v=$(compgen -v | sort); before_o=$(set +o); before_t=$(trap -p)',
    `. ${JSON.stringify(TABLE)} > "$OUT" 2>&1`,
    'after_f=$(declare -F | sort); after_v=$(compgen -v | sort); after_o=$(set +o); after_t=$(trap -p)',
    'comm -13 <(printf "%s\\n" "$before_f") <(printf "%s\\n" "$after_f")',
    'echo ---',
    'comm -13 <(printf "%s\\n" "$before_v") <(printf "%s\\n" "$after_v") | grep -v -e "^before_" -e "^after_" -e "^_$" || true',
    'echo ---',
    '[ "$before_o" = "$after_o" ] && echo options-same',
    '[ "$before_t" = "$after_t" ] && echo traps-same',
  ].join('\n');
  const root = path.join(REPO, 'test');
  const out = path.join(tempDir(t, 'doflow-emission-out-'), 'out');
  const result = spawnSync(BASH, ['-c', script], { cwd: root, encoding: 'utf8', env: { PATH: process.env.PATH, OUT: out } });
  assert.equal(result.status, 0, result.stderr);
  const [funcs, vars, rest] = result.stdout.split('---\n');
  assert.deepEqual(funcs.trim().split('\n'), ['declare -f doflow_emission_rule']);
  assert.deepEqual(vars.trim().split('\n').sort(), [
    'DF_RULES_MAX_BYTES_DEFAULT', 'DF_RULES_SUMMARY_CAP', 'DF_RULES_SUMMARY_READ', 'DF_RULES_VERSION',
  ]);
  assert.deepEqual(rest.trim().split('\n'), ['options-same', 'traps-same']);
  assert.equal(fs.readFileSync(out, 'utf8'), '');
});

test('IC-003 a lookup sets DF_ACTION in the calling shell, with no subshell', () => {
  const script = [
    'set -euo pipefail',
    `. ${JSON.stringify(TABLE)}`,
    'DF_ACTION=unset',
    'doflow_emission_rule prompt.git main:false; echo "$DF_ACTION"',
    'doflow_emission_rule prompt.git worker:false; echo "$DF_ACTION"',
    'doflow_emission_rule prompt.grant false:fits:true; echo "$DF_ACTION"',
    "doflow_emission_rule 'prompt.git' '*'; echo \"$DF_ACTION\"",
    'doflow_emission_rule no.such vector; echo "$?:$DF_ACTION"',
  ].join('\n');
  // HOME is passed because the macOS runner image (from 2026-10-15) prints "$HOME must be set to
  // run brew." on stderr for a child started without it; the table itself runs no command.
  const result = spawnSync(BASH, ['-c', script], { encoding: 'utf8', env: { PATH: process.env.PATH, HOME: process.env.HOME } });
  assert.equal(result.status, 0, result.stderr);
  assert.deepEqual(result.stdout.trim().split('\n'), ['include', 'skip', 'whole', 'skip', '0:skip']);
  assert.equal(result.stderr, '');
});

test('IC-003 /bin/bash -n parses the committed table', () => {
  const result = spawnSync(BASH, ['-n', TABLE], { encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);
});
