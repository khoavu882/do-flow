/**
 * `review-pack --task-id <slug>` and `roadmap --action report`: the one place a person reviews what an
 * unattended run decided. Both read records and write a Markdown file; neither calls a model, and
 * every line is something a record states, with no judgement and no score. A section a record does
 * not fill says "none recorded" rather than being left out, and what the records cannot show is
 * listed last, under "Not verified". The same records give the same bytes except the one
 * `Generated at` line.
 *
 * `review-pack` is the `/do-flow` finishing step; `roadmap --action report` is one table per roadmap
 * run, which generates the pack of any row that has none.
 */

