/** The branch and its head: the run record's branch when it names one, else the current branch when it ends `/<slug>`, else `feat/<slug>`. */
function gatherBranch({ cwd, slug, run }: any): { branch: string | null; head: string | null } {
  const candidates: string[] = [];
  for (const named of [run?.commit?.branch, run?.branch]) if (typeof named === 'string' && named) candidates.push(named);
  const current = git(cwd, ['branch', '--show-current']);
  if (current && current.endsWith(`/${slug}`)) candidates.push(current);
  candidates.push(`feat/${slug}`);
  for (const candidate of [...new Set(candidates)]) {
    const sha = git(cwd, ['rev-parse', '--verify', '--quiet', `refs/heads/${candidate}`]);
    if (sha) return { branch: candidate, head: sha };
  }
  return { branch: null, head: null };
}

function gatherResult({ cwd, slug, run, seedRow }: any): any {
  const { branch, head } = gatherBranch({ cwd, slug, run });
  const nodes: any[] = Array.isArray(run?.program) ? run.program : [];
  const stages = nodes.filter((n) => n?.type === 'stage');
  const lastDone = [...stages].reverse().find(isNodeDone);
  const at = Number.isInteger(run?.cursor) && run.cursor < nodes.length ? nodes[run.cursor] : null;
  return {
    taskClass: run?.taskClass ?? seedRow?.class ?? null,
    branch, head, mergeCommit: seedRow?.mergeCommit ?? null,
    runState: run?.state ?? null,
    lastStage: lastDone?.id ?? null,
    current: at ? `${at.type} ${at.id}` : null,
    progress: run ? `${nodes.filter(isNodeDone).length} of ${nodes.length} steps done` : null,
  };
}

function gatherGates({ run, register }: any): any[] {
  if (!run || !Array.isArray(run.program)) return [];
  const history: any[] = Array.isArray(run.history) ? run.history : [];
  const policyDecisions: any[] = (register?.decisions || []).filter((d: any) => d.channel === 'policy');
  return run.program.filter((n: any) => n?.type === 'gate').map((gate: any) => {
    const entry = [...history].reverse().find((h) => h?.action === 'decide-gate' && h.node === gate.id);
    if (!entry) return { id: gate.id, status: gate.status ?? 'pending' };
    const policy = entry.by === 'autopilot';
    // The inputs digest is in the register's policy entry for this gate, not in the journal.
    const registered = [...policyDecisions].reverse().find((d) => d.topic === gate.id);
    const digest = /inputs digest (sha256:[0-9a-f]+|[0-9a-f]{8,})/i.exec(String(registered?.rationale ?? ''))?.[1] ?? null;
    // The journal records no person: a decision that is not the policy's has no named actor unless the entry names one.
    const actor = !policy && typeof entry.by === 'string' && entry.by ? entry.by : null;
    return {
      id: gate.id, status: gate.status ?? null, decided: true, decision: entry.detail ?? null, policy, actor, at: entry.at ?? null,
      forced: entry.forced === true, note: entry.note ?? null,
      ...(policy ? { policyRef: entry.policy ?? null, inputs: Array.isArray(entry.inputs) ? entry.inputs.length : null, inputsDigest: digest } : {}),
    };
  });
}

function gatherVerification({ slug, run, root, fsImpl }: any): any {
  const file = verificationRunRecordFile(verificationRunsRoot(root), run?.taskId || slug);
  let text: string;
  try { text = fsImpl.readFileSync(file, 'utf8'); } catch (error: any) {
    return { runs: [], unreadable: 0, error: error && error.code === 'ENOENT' ? null : `${path.basename(file)}: ${error?.message ?? error}` };
  }
  const runs: any[] = [];
  let unreadable = 0;
  for (const line of text.split('\n')) {
    if (!line.trim()) continue;
    try { const r = JSON.parse(line); if (r && typeof r === 'object' && !Array.isArray(r)) runs.push(r); else unreadable += 1; } catch { unreadable += 1; }
  }
  return { runs, unreadable, error: null };
}

/** `review/findings.json` through the review record's own validator: absent, unreadable, invalid or the record. */
function gatherReview({ featureDir, fsImpl }: any): any {
  const read = readJsonState(path.join(featureDir, 'review', 'findings.json'), fsImpl);
  if (read.state === 'absent') return { state: 'absent' };
  if (read.state === 'unreadable') return { state: 'unreadable', reason: read.reason };
  let verdict: any;
  try { verdict = validateFindings(read.value); } catch (error: any) { verdict = { ok: false, errors: [`validator: ${error?.message ?? error}`] }; }
  if (!verdict.ok) return { state: 'invalid', errors: verdict.errors };
  const data = read.value;
  const seats: any[] = Array.isArray(data.seats) ? data.seats : [];
  const converged: any[] = Array.isArray(data.converged) ? data.converged : [];
  return { state: 'ok', data, seats, converged, seatFindings: seats.flatMap((s) => (Array.isArray(s?.findings) ? s.findings : [])) };
}

/** The roadmap run records under `dir`, oldest first: the readable ones, and the names of those that could not be read. */
function readRunRecords(dir: string, fsImpl: any): { records: any[]; unreadable: string[] } {
  let names: string[];
  try { names = fsImpl.readdirSync(dir); } catch (error: any) {
    return { records: [], unreadable: error && error.code === 'ENOENT' ? [] : [`${path.basename(dir)} (${error?.message ?? error})`] };
  }
  const records: any[] = [];
  const unreadable: string[] = [];
  for (const name of names.filter((n) => /^rl-.*\.json$/.test(n)).sort()) {
    try { const record = readRunFile(path.join(dir, name), fsImpl); if (record) records.push(record); } catch { unreadable.push(name); }
  }
  records.sort((a, b) => (a.createdAt < b.createdAt ? -1 : a.createdAt > b.createdAt ? 1 : a.runId < b.runId ? -1 : 1));
  return { records, unreadable };
}

function gatherOpen({ slug, featureDir, root, run, seedRow, fsImpl }: any): any {
  let followups: any[] = [];
  let followupsError: string | null = null;
  let followupsUnreadable: string[] = [];
  try {
    const fold = readFold(lifecycleProjectRoot(root), { hasBody: () => false, fsImpl });
    followups = (fold.followups || []).filter((item: any) => item?.source?.feature === slug || (item?.source?.kind === 'run' && item.source.taskId === slug));
    if (Array.isArray(fold.unreadable)) followupsUnreadable = fold.unreadable.map((f: any) => path.basename(String(f)));
  } catch (error: any) { followupsError = String(error?.message ?? error); }
  const holds: any[] = [];
  const { records, unreadable } = readRunRecords(path.join(resolveMainRoot(root), '.doflow', 'state', 'roadmap', 'runs'), fsImpl);
  const newest = [...records].reverse().find((r) => seedRow && r.rows && r.rows[seedRow.id]);
  const slot = newest?.rows?.[seedRow?.id];
  if (slot?.held) holds.push({ kind: 'held', runId: newest.runId, type: slot.held.kind ?? null, reason: slot.held.reason ?? null });
  if (slot?.paused) holds.push({ kind: 'paused', runId: newest.runId, type: null, reason: slot.paused.reason ?? null });
  if (run?.state === 'REJECTED') holds.push({ kind: 'rejected', runId: null, type: null, reason: 'the run journal records a rejected gate' });
  const markers: any[] = [];
  const markersUnreadable: string[] = [];
  for (const rel of MARKER_FILES) {
    let text: string;
    try { text = fsImpl.readFileSync(path.join(featureDir, rel), 'utf8'); } catch (error: any) {
      if (error && error.code !== 'ENOENT' && error.code !== 'ENOTDIR') markersUnreadable.push(rel);
      continue;
    }
    const count = countMarkers(text);
    if (count > 0) markers.push({ file: rel, count });
  }
  return { followups, followupsError, followupsUnreadable, holds, markers, markersUnreadable, runRecordsUnreadable: unreadable };
}

function seedRowFor(root: string, slug: string, fsImpl: any): { row: any; error: string | null } {
  const file = path.join(resolveMainRoot(root), 'agent-docs', 'roadmap', 'rows.json');
  let text: string;
  try { text = fsImpl.readFileSync(file, 'utf8'); } catch (error: any) {
    return { row: null, error: error && error.code === 'ENOENT' ? null : `rows.json: ${error?.message ?? error}` };
  }
  try { return { row: parseSeed(text).rows.find((r: any) => r.slug === slug) || null, error: null }; } catch (error: any) {
    return { row: null, error: `rows.json: ${error?.message ?? error}` };
  }
}

/** Everything the pack states, read once, all from the one feature root `feature.featureRoot`. `feature` is a `resolveFeature` result. */
function gatherFacts({ cwd, slug, feature, fsImpl = nodeFs }: any): any {
  const root = feature.featureRoot;
  const featureDir = feature.featureFolder;
  let register: any = null;
  let registerError: string | null = null;
  try { register = readRegister(featureDir, fsImpl); } catch (error: any) { registerError = String(error?.message ?? error); }
  const found = findRunFile({ stateRoot: root, taskId: slug, slug });
  let run: any = null;
  let runError: string | null = null;
  if (found.status === 'found') {
    try { run = readRunRecord(fsImpl, found.file, runStoreDir(found.root)); } catch (error: any) { runError = String(error?.message ?? error); }
  } else if (found.status === 'ambiguous') runError = `the run of '${slug}' is in more than one checkout`;
  const seed = seedRowFor(root, slug, fsImpl);
  const result = gatherResult({ cwd, slug, run, seedRow: seed.row });
  return {
    slug, root, featureDir, run, runError, register, registerError, seedRow: seed.row, seedError: seed.error,
    result,
    // 181 IC-010: what ran on the head, from the verify record and the evidence ledger; nothing without a head.
    whatRan: result.head ? compileRunEvidence({ root, taskId: run?.taskId || slug, head: result.head, fsImpl, featureDir }) : null,
    decisions: register?.decisions || [],
    gates: gatherGates({ run, register }),
    verification: gatherVerification({ slug, run, root, fsImpl }),
    review: gatherReview({ featureDir, fsImpl }),
    open: gatherOpen({ slug, featureDir, root, run, seedRow: seed.row, fsImpl }),
  };
}

/** The counts one roadmap report row needs, taken from the same facts the pack prints. */
function countsOf(facts: any): { agent: number; autopilot: number; user: number; open: number } {
  const by = (who: string) => facts.decisions.filter((d: any) => d.decidedBy === who).length;
  const openFollowups = facts.open.followups.filter((f: any) => f.state === 'open' || f.state === 'taken').length;
  const markers = facts.open.markers.reduce((n: number, m: any) => n + m.count, 0);
  return { agent: by('agent'), autopilot: by('autopilot'), user: by('user'), open: openFollowups + facts.open.holds.length + markers };
}

// ── render ─────────────────────────────────────────────────────────────────────────────────────

function sectionResult(f: any): string[] {
  const r = f.result;
  const out = [
    `- Task class: ${r.taskClass ? clean(r.taskClass) : NONE}`,
    `- Branch: ${r.branch ? clean(r.branch) : NOT_DETERMINED}`,
    `- Head commit: ${r.head ? clean(r.head) : NOT_DETERMINED}`,
    `- Merge commit: ${r.mergeCommit ? clean(r.mergeCommit) : NONE}`,
  ];
  if (!f.run) {
    out.push(`- Stage reached: ${NONE}`);
  } else {
    out.push(`- Run state: ${clean(r.runState)}${r.current ? `, at ${clean(r.current)}` : ''} (${clean(r.progress)})`);
    out.push(`- Stage reached: ${r.lastStage ? clean(r.lastStage) : 'no stage completed'}`);
  }
  out.push(`- ${flowCountLine(f.whatRan)}`);
  return out;
}

/** IC-010: the count of user-facing flows by what ran on the head, never a verified claim for a flow that did not run. */
function flowCountLine(w: any): string {
  if (!w) return `User-facing flows: ${NOT_DETERMINED}`;
  if (w.featureMap === 'absent') return 'User-facing flows: no feature map';
  if (w.featureMap === 'invalid' && w.flows.length === 0) return 'User-facing flows: the feature map is invalid';
  const n = (status: string) => w.flows.filter((x: any) => x.status === status).length;
  return `User-facing flows run on head: ${n('passed')} passed, ${n('failed')} failed, ${n('unreached')} unreached, ${n('not-run')} not run (of ${w.flows.length})`;
}

/** IC-010 section 2: each check of the latest verify run on the head, then each flow that has an outcome on it. */
function sectionWhatRan(f: any): string[] {
  const w = f.whatRan;
  if (!w) return ['- The head commit is not determined: nothing is shown as run on it.'];
  const out: string[] = [];
  for (const c of w.verify?.checks ?? []) {
    out.push(`- ${clean(c.tier)} · ${clean(c.command ?? NONE)} · ${clean(c.status)} · exit ${c.exitCode === null || c.exitCode === undefined ? NONE : clean(c.exitCode)} · commit ${short(w.head)}`);
  }
  for (const x of w.flows.filter((flow: any) => flow.status !== 'not-run')) {
    out.push(`- flow ${clean(x.id)} · ${clean(x.action ?? NONE)} · ${clean(x.status)} · ${clean(x.observed ?? NONE)} · ${clean(x.locator ?? NONE)} · commit ${short(x.commit)}`);
  }
  return out.length ? out : [`- ${NONE}`];
}

function sectionDecisions(f: any): string[] {
  const listed = f.decisions.filter((d: any) => d.decidedBy === 'agent' || d.decidedBy === 'autopilot');
  const users = f.decisions.filter((d: any) => d.decidedBy === 'user').length;
  const out: string[] = [];
  if (listed.length === 0) out.push(`- ${NONE}`);
  for (const d of listed) {
    out.push(`- ${clean(d.id)} · ${clean(d.stage)} · ${clean(d.topic)} · by ${clean(d.decidedBy)}${d.status === 'live' ? '' : ` · superseded by ${clean(d.supersededBy)}`}${d.retired ? ' · retired' : ''}`);
    out.push(`  - Decision: ${clean(d.statement)}`);
    out.push(`  - Reason: ${clean(d.rationale)}`);
    out.push(`  - Undo: ${d.undo ? clean(d.undo) : NONE}`);
  }
  out.push('', `Decisions by the user: ${users}`);
  return out;
}

function sectionGates(f: any): string[] {
  if (f.gates.length === 0) return [`- ${NONE}`];
  return f.gates.map((g: any) => {
    if (!g.decided) return `- ${clean(g.id)}: ${g.status === 'pending' ? 'no decision recorded' : `status ${clean(g.status)}`}`;
    const by = g.policy ? 'by policy' : g.actor ? `by ${clean(g.actor)}` : 'not by policy (actor not recorded)';
    const base = `- ${clean(g.id)}: ${clean(g.decision ?? g.status)} ${by}${g.forced ? ' (forced)' : ''} at ${g.at ? clean(g.at) : NONE}`;
    if (!g.policy) return g.note ? `${base}; note: ${clean(g.note)}` : base;
    const ref = g.policyRef ? `policy ${clean(g.policyRef.id)}@${clean(g.policyRef.digest ?? NONE)}` : 'policy not recorded';
    return `${base}; ${ref}; ${g.inputs ?? NONE} inputs; inputs digest ${g.inputsDigest ? clean(g.inputsDigest) : NONE}`;
  });
}

function sectionVerification(f: any): string[] {
  const { runs, unreadable } = f.verification;
  const out: string[] = [];
  if (runs.length === 0) out.push(`- ${NONE}`);
  for (const r of runs) {
    out.push(`- ${clean(r.at ?? NONE)} · ${clean(r.verdict ?? NONE)} · risk ${clean(r.risk ?? NONE)} · commit ${short(r.head)} · tree ${r.clean === true ? 'clean' : r.clean === false ? 'dirty' : NONE} · report ${short(String(r.reportSha256 ?? '').replace(/^sha256:/, ''))}`);
  }
  const latest = runs[runs.length - 1];
  if (latest && f.result.head) {
    out.push('', latest.head === f.result.head
      ? `The latest run is on the head commit (${short(f.result.head)}).`
      : `The latest run is not on the head commit: it ran on ${short(latest.head)}, the head is ${short(f.result.head)}.`);
  }
  if (unreadable) out.push('', `${unreadable} verify record line(s) could not be read.`);
  return out;
}

function sectionReview(f: any): string[] {
  const r = f.review;
  if (r.state !== 'ok') return [`- ${NONE}`];
  const sev = (list: any[], s: string) => list.filter((x) => x?.severity === s).length;
  const out = [
    `- Seats: ${r.seats.length}${r.seats.length ? ` (${r.seats.map((s: any) => clean(s?.id)).join(', ')})` : ''}`,
    `- Rounds: ${r.data.rounds === undefined ? NONE : clean(r.data.rounds)}`,
    `- Reviewed head: ${r.data.reviewedHead === undefined ? NONE : clean(r.data.reviewedHead)}`,
    `- Seat findings: ${r.seatFindings.length} (blocker ${sev(r.seatFindings, 'blocker')}, should-fix ${sev(r.seatFindings, 'should-fix')}, note ${sev(r.seatFindings, 'note')})`,
  ];
  const status = (s: string) => r.converged.filter((x: any) => x?.status === s).length;
  out.push(`- Converged findings: ${r.converged.length} (blocker ${sev(r.converged, 'blocker')}, should-fix ${sev(r.converged, 'should-fix')}, note ${sev(r.converged, 'note')}); fixed ${status('fixed')}, refuted ${status('refuted')}, user-accepted ${status('user-accepted')}, open ${status('open')}`);
  const accepted = r.converged.filter((x: any) => x?.status === 'user-accepted');
  if (accepted.length === 0) out.push(`- Accepted without a fix: ${NONE}`);
  else {
    out.push('- Accepted without a fix:');
    for (const x of accepted) out.push(`  - ${clean(x.id)} · ${clean(x.severity)} · ${clean(x.locator)} · ${clean(x.summary)}${x.acceptedAs ? ` · ${clean(x.acceptedAs)}` : ''}${x.decision ? ` · ${clean(x.decision)}` : ''}`);
  }
  return out;
}

function sectionOpen(f: any): string[] {
  const o = f.open;
  const out: string[] = [];
  if (o.followups.length === 0) out.push(`- Follow-ups: ${NONE}`);
  else {
    out.push('- Follow-ups:');
    for (const item of o.followups) out.push(`  - ${clean(item.id)} · ${clean(item.state)} · ${clean(item.source?.stage ?? NONE)} · ${clean(item.statement)}`);
  }
  if (o.holds.length === 0) out.push(`- Holds: ${NONE}`);
  else {
    out.push('- Holds:');
    for (const h of o.holds) out.push(`  - ${clean(h.kind)}${h.type ? ` (${clean(h.type)})` : ''}${h.runId ? ` in ${clean(h.runId)}` : ''}: ${clean(h.reason ?? NONE)}`);
  }
  if (o.markers.length === 0) out.push(`- Unresolved clarification markers: ${NONE}`);
  else {
    out.push('- Unresolved clarification markers:');
    for (const m of o.markers) out.push(`  - ${clean(m.file)}: ${m.count}`);
  }
  return out;
}

/** IC-010: flows with no run on the head, a missing or invalid map, and a verify run that is not evidence for the head. */
function notVerifiedRunEvidence(f: any): string[] {
  const w = f.whatRan;
  if (!w) return [];
  const out: string[] = [];
  if (w.verify && !w.verify.onHead) out.push('- The latest verify run is not on the head commit; its checks are not shown as evidence for this head.');
  else if (w.verify && w.verify.clean !== true) out.push('- The latest verify run was on a tree with uncommitted changes; its checks are not shown as evidence for this head.');
  if (w.featureMap === 'absent') out.push('- No feature map: no user-facing flow is shown as run.');
  if (w.featureMap === 'invalid') out.push('- The feature map is invalid: a flow it lists is not shown as run unless it has a result on the head.');
  for (const x of w.flows.filter((flow: any) => flow.status === 'not-run')) out.push(`- Flow ${clean(x.id)} (${clean(x.title)}): not run on ${short(w.head)}`);
  for (const problem of w.problems) out.push(`- Run evidence: ${clean(problem)}`);
  return out;
}

function sectionNotVerified(f: any): string[] {
  const out: string[] = [];
  if (f.registerError) out.push(`- The decision register could not be read: ${clean(f.registerError)}`);
  else if (!f.register) out.push('- No decision register (decisions/register.json): decisions are not shown.');
  if (f.runError) out.push(`- The orchestration run could not be read: ${clean(f.runError)}`);
  else if (!f.run) out.push('- No orchestration run on record: task class, stage and gates are not shown.');
  if (f.seedError) out.push(`- The roadmap seed could not be read: ${clean(f.seedError)}; the merge commit and the holds of this row are not shown.`);
  if (!f.result.head) out.push(`- No branch was determined for this feature (the run record's, the current branch ending /${clean(f.slug)}, feat/${clean(f.slug)}): the head commit is not shown, and verify runs cannot be compared with it.`);
  const v = f.verification;
  if (v.error) out.push(`- The verify record could not be read: ${clean(v.error)}`);
  else if (v.runs.length === 0 && v.unreadable === 0) out.push('- No verify run on record.');
  else if (v.runs.length > 0 && v.runs[v.runs.length - 1].schema === 1) out.push('- The verify record predates check details; its commands are not shown.');
  if (v.unreadable) out.push(`- ${v.unreadable} line(s) of the verify record could not be read.`);
  out.push(...notVerifiedRunEvidence(f));
  const r = f.review;
  if (r.state === 'absent') out.push('- No review on record (no review/findings.json).');
  else if (r.state === 'unreadable') out.push(`- The review record could not be read: ${clean(r.reason)}`);
  else if (r.state === 'invalid') out.push(`- review/findings.json is not a valid review record (${r.errors.map(clean).join(', ')}): the review is not shown.`);
  const o = f.open;
  if (o.followupsError) out.push(`- The follow-up store could not be read: ${clean(o.followupsError)}; follow-ups are not shown.`);
  if (o.followupsUnreadable.length) out.push(`- ${o.followupsUnreadable.length} follow-up event file(s) could not be read: ${o.followupsUnreadable.map(clean).join(', ')}.`);
  if (o.runRecordsUnreadable.length) out.push(`- Roadmap run record(s) could not be read: ${o.runRecordsUnreadable.map(clean).join(', ')}; the holds of this row may be incomplete.`);
  if (o.markersUnreadable.length) out.push(`- Artifact file(s) could not be read for clarification markers: ${o.markersUnreadable.map(clean).join(', ')}.`);
  if (out.length === 0) out.push(`- ${NONE}`);
  return out;
}

function renderPack(f: any, now: Date): string {
  const sections: Array<[string, string[]]> = [
    ['Result', sectionResult(f)],
    ['What ran', sectionWhatRan(f)],
    ['Decisions taken for you', sectionDecisions(f)],
    ['Gates', sectionGates(f)],
    ['Verification', sectionVerification(f)],
    ['Review', sectionReview(f)],
    ['Open items', sectionOpen(f)],
    ['Not verified', sectionNotVerified(f)],
  ];
  const out = [`# Review pack: ${clean(f.slug)}`, '', `> ${GENERATED_NOTE}`, '', `Generated at: ${now.toISOString()}`];
  sections.forEach(([title, lines], i) => out.push('', `## ${i + 1}. ${title}`, '', ...lines));
  return `${out.join('\n')}\n`;
}

/** Writes `content` to `file` by an exclusively created temp file with an unpredictable name, then a rename. */
function writeAtomic(fsImpl: any, file: string, content: string): void {
  fsImpl.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.${crypto.randomBytes(8).toString('hex')}.tmp`;
  let created = false;
  try {
    fsImpl.writeFileSync(tmp, content, { encoding: 'utf8', flag: 'wx' });
    created = true;
    fsImpl.renameSync(tmp, file);
  } catch (error: any) {
    if (created) { try { fsImpl.rmSync(tmp, { force: true }); } catch { /* nothing to clean */ } }
    throw error;
  }
}

