/** Builds and writes the pack of `slug`. Returns `{ok:false, message}` when the feature does not resolve. */
function writeReviewPack({ cwd, slug, now = new Date(), fsImpl = nodeFs }: any): any {
  const feature = resolveFeature(cwd, slug);
  if (feature.error) return { ok: false, message: feature.message };
  if (!isDir(feature.featureFolder, fsImpl)) return { ok: false, message: `'${slug}' has no feature folder (${feature.featureFolder})` };
  const facts = gatherFacts({ cwd, slug, feature, fsImpl });
  const file = path.join(facts.featureDir, PACK_FILE);
  writeAtomic(fsImpl, file, renderPack(facts, now));
  return { ok: true, slug, path: file, counts: countsOf(facts), facts };
}

function handleReviewPackCommand({ taskId, cwd = process.cwd(), json = false, now = new Date(), fsImpl = nodeFs }: any = {}): number {
  if (typeof taskId !== 'string' || taskId === '') return usageError('review-pack', '--task-id <feature slug> is required', json);
  if (!isSafeSlug(taskId)) return usageError('review-pack', `'${taskId}' is not a feature slug`, json);
  const result = writeReviewPack({ cwd, slug: taskId, now, fsImpl });
  if (!result.ok) return usageError('review-pack', result.message, json);
  if (json) console.log(JSON.stringify({ v: 1, slug: result.slug, path: result.path, counts: result.counts }, null, 2));
  else console.log(result.path);
  return finishRuntime(0);
}

/** `roadmap --action report [--run <id>]` as data: the table rows and the report text. */
function buildRoadmapReport({ cwd, runId, now = new Date(), fsImpl = nodeFs }: any): any {
  const root = resolveMainRoot(cwd);
  const runsDir = path.join(root, '.doflow', 'state', 'roadmap', 'runs');
  const records = readRunRecords(runsDir, fsImpl);
  const run = runId ? records.find((r) => r.runId === runId) : records[records.length - 1];
  if (!run) return { ok: false, message: runId ? `no roadmap run record '${runId}' under ${runsDir}` : `no roadmap run record under ${runsDir}` };
  let seedRows: any[] = [];
  try { seedRows = parseSeed(fsImpl.readFileSync(path.join(root, 'agent-docs', 'roadmap', 'rows.json'), 'utf8')).rows; } catch { /* rows without a seed row show no title */ }
  const statuses = roadmapStatusResult({ json: true, root, cwd, fsImpl }).json?.rowStatus || {};
  const order = new Map(seedRows.map((r: any, i: number) => [r.id, i]));
  const ids = Object.keys(run.rows).sort((a, b) => (order.get(a) ?? 1e9) - (order.get(b) ?? 1e9) || (a < b ? -1 : 1));
  const rows = ids.map((id) => {
    const seed = seedRows.find((r: any) => r.id === id) || null;
    const slot = run.rows[id] || {};
    const held = slot.held ? `held (${slot.held.kind ?? 'unknown'}): ${slot.held.reason ?? NONE}` : slot.paused ? `paused: ${slot.paused.reason ?? NONE}` : null;
    const row: any = { row: id, title: seed?.title ?? null, class: seed?.class ?? null, status: statuses[id] ?? null, held, decisions: null, openItems: null, pack: null, packNote: null };
    if (!seed) { row.packNote = 'row not in the seed'; return row; }
    const feature = resolveFeature(cwd, seed.slug);
    if (feature.error || !isDir(feature.featureFolder, fsImpl)) { row.packNote = `no feature folder: ${feature.error ? feature.message : feature.featureFolder}`; return row; }
    const facts = gatherFacts({ cwd, slug: seed.slug, feature, fsImpl });
    const counts = countsOf(facts);
    row.decisions = counts.agent + counts.autopilot;
    row.openItems = counts.open;
    const file = path.join(facts.featureDir, PACK_FILE);
    if (!fsImpl.existsSync(file)) writeAtomic(fsImpl, file, renderPack(facts, now));
    row.pack = path.relative(root, file).startsWith('..') ? file : path.relative(root, file);
    return row;
  });
  const lines = [
    `# Roadmap run report: ${run.runId}`, '', `> Generated by \`doflow-run roadmap --action report\` from the roadmap run record and each row's records. It states what they state and nothing else. Do not edit this file.`, '',
    `Generated at: ${now.toISOString()}`, '',
    `Run created ${run.createdAt ?? NONE}; ${run.closedAt ? `closed ${run.closedAt}` : 'not closed'}; ${run.steps} step(s) taken.`, '',
  ];
  if (rows.length === 0) lines.push(`Rows: ${NONE}`);
  else {
    lines.push('| Row | Title | Class | Status | Held | Agent or autopilot decisions | Open items | Review pack |', '|---|---|---|---|---|---|---|---|');
    for (const r of rows) {
      lines.push(`| ${cell(r.row)} | ${cell(r.title ?? NONE)} | ${cell(r.class ?? NONE)} | ${cell(r.status ?? NONE)} | ${cell(r.held ?? 'no')} | ${r.decisions ?? NONE} | ${r.openItems ?? NONE} | ${cell(r.pack ?? r.packNote ?? NONE)} |`);
    }
  }
  return { ok: true, runId: run.runId, root, rows, text: `${lines.join('\n')}\n`, file: path.join(runsDir, `${run.runId}.report.md`) };
}

function handleRoadmapReportCommand({ runId, cwd = process.cwd(), json = false, now = new Date(), fsImpl = nodeFs }: any = {}): number {
  if (runId !== undefined && !RUN_ID.test(String(runId))) return usageError('roadmap', '--run must be rl-<yyyymmdd>-<4 crockford characters>', json);
  const report = buildRoadmapReport({ cwd, runId, now, fsImpl });
  if (!report.ok) return usageError('roadmap', report.message, json);
  writeAtomic(fsImpl, report.file, report.text);
  if (json) console.log(JSON.stringify({ schema: 1, action: 'report', runId: report.runId, path: report.file, rows: report.rows }));
  else { process.stdout.write(report.text); console.log(`written: ${report.file}`); }
  return finishRuntime(0);
}

