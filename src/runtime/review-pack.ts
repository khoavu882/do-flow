/** Builds and writes the pack of `slug` into the one feature folder it resolved. Returns `{ok:false, message}` when the feature does not resolve or the folder is not inside its checkout. */
function writeReviewPack({ cwd, slug, now = new Date(), fsImpl = nodeFs }: any): any {
  const feature = resolveFeature(cwd, slug);
  if (feature.error) return { ok: false, message: plain(feature.message) };
  if (!isDir(feature.featureFolder, fsImpl)) return { ok: false, message: `'${plain(slug)}' has no feature folder (${plain(feature.featureFolder)})` };
  if (!insideRoot(feature.featureFolder, feature.featureRoot, fsImpl)) return { ok: false, message: `the feature folder of '${plain(slug)}' resolves outside its checkout (${plain(feature.featureFolder)}); nothing was written` };
  const facts = gatherFacts({ cwd, slug, feature, fsImpl });
  const file = path.join(facts.featureDir, PACK_FILE);
  writeAtomic(fsImpl, file, renderPack(facts, now));
  return { ok: true, slug, path: file, counts: countsOf(facts), facts };
}

function handleReviewPackCommand({ taskId, cwd = process.cwd(), json = false, now = new Date(), fsImpl = nodeFs }: any = {}): number {
  if (typeof taskId !== 'string' || taskId === '') return usageError('review-pack', '--task-id <feature slug> is required', json);
  if (!isSafeSlug(taskId)) return usageError('review-pack', `'${plain(taskId).slice(0, 80)}' is not a feature slug`, json);
  const result = writeReviewPack({ cwd, slug: taskId, now, fsImpl });
  if (!result.ok) return usageError('review-pack', result.message, json);
  if (json) console.log(JSON.stringify({ v: 1, slug: result.slug, path: result.path, counts: result.counts }, null, 2));
  else console.log(plain(result.path));
  return finishRuntime(0);
}

/** `roadmap --action report [--run <id>]` as data: the table rows and the report text. Every row's pack is regenerated. */
function buildRoadmapReport({ cwd, runId, now = new Date(), fsImpl = nodeFs }: any): any {
  const root = resolveMainRoot(cwd);
  const runsDir = path.join(root, '.doflow', 'state', 'roadmap', 'runs');
  const { records, unreadable } = readRunRecords(runsDir, fsImpl);
  const run = runId ? records.find((r) => r.runId === runId) : records[records.length - 1];
  if (!run) {
    const named = runId ? `no roadmap run record '${runId}' under ${runsDir}` : `no roadmap run record under ${runsDir}`;
    return { ok: false, message: plain(unreadable.length ? `${named} (unreadable: ${unreadable.join(', ')})` : named) };
  }
  let seedRows: any[] = [];
  let seedNote: string | null = null;
  try { seedRows = parseSeed(fsImpl.readFileSync(path.join(root, 'agent-docs', 'roadmap', 'rows.json'), 'utf8')).rows; } catch (error: any) {
    if (!error || error.code !== 'ENOENT') seedNote = `The roadmap seed could not be read (${error?.message ?? error}): no row has a title or a pack.`;
  }
  const statusResult = roadmapStatusResult({ json: true, root, cwd, fsImpl }).json;
  const statuses = statusResult?.rowStatus || {};
  const statusNote = statusResult?.rowStatus ? null : `Row status is not shown: ${statusResult?.message ?? statusResult?.error ?? 'the status could not be read'}.`;
  const order = new Map(seedRows.map((r: any, i: number) => [r.id, i]));
  const ids = Object.keys(run.rows).sort((a, b) => (order.get(a) ?? 1e9) - (order.get(b) ?? 1e9) || (a < b ? -1 : 1));
  const rows = ids.map((id) => {
    const seed = seedRows.find((r: any) => r.id === id) || null;
    const slot = run.rows[id] || {};
    const held = slot.held ? `held (${slot.held.kind ?? 'unknown'}): ${slot.held.reason ?? NONE}` : slot.paused ? `paused: ${slot.paused.reason ?? NONE}` : null;
    const row: any = { row: id, title: seed?.title ?? null, class: seed?.class ?? null, status: statuses[id] ?? null, held, decisions: null, openItems: null, pack: null, packNote: null };
    if (!seed) { row.packNote = 'row not in the seed'; return row; }
    if (!isSafeSlug(seed.slug)) { row.packNote = 'the seed row has no usable slug'; return row; }
    const made = writeReviewPack({ cwd, slug: seed.slug, now, fsImpl });
    if (!made.ok) { row.packNote = `no pack: ${made.message}`; return row; }
    row.decisions = made.counts.agent + made.counts.autopilot;
    row.openItems = made.counts.open;
    const rel = path.relative(root, made.path);
    row.pack = rel.startsWith('..') ? made.path : rel;
    return row;
  });
  const lines = [
    `# Roadmap run report: ${clean(run.runId)}`, '', `> Generated by \`doflow-run roadmap --action report\` from the roadmap run record and each row's records. It states what they state and nothing else. Do not edit this file.`, '',
    `Generated at: ${now.toISOString()}`, '',
    `Run created ${clean(run.createdAt ?? NONE)}; ${run.closedAt ? `closed ${clean(run.closedAt)}` : 'not closed'}; ${clean(run.steps)} step(s) taken.`, '',
  ];
  if (unreadable.length) lines.push(`Run record(s) that could not be read: ${unreadable.map(clean).join(', ')}.`, '');
  if (seedNote) lines.push(clean(seedNote), '');
  if (statusNote) lines.push(clean(statusNote), '');
  if (rows.length === 0) lines.push(`Rows: ${NONE}`);
  else {
    lines.push('| Row | Title | Class | Status | Held | Agent or autopilot decisions | Open items | Review pack |', '|---|---|---|---|---|---|---|---|');
    for (const r of rows) {
      lines.push(`| ${cell(r.row)} | ${cell(r.title ?? NONE)} | ${cell(r.class ?? NONE)} | ${cell(r.status ?? NONE)} | ${cell(r.held ?? 'no')} | ${r.decisions ?? NONE} | ${r.openItems ?? NONE} | ${cell(r.pack ?? r.packNote ?? NONE)} |`);
    }
  }
  return { ok: true, runId: run.runId, root, rows, text: `${lines.join('\n')}\n`, file: path.join(root, 'agent-docs', 'roadmap', REPORT_FILE) };
}

function handleRoadmapReportCommand({ runId, cwd = process.cwd(), json = false, now = new Date(), fsImpl = nodeFs }: any = {}): number {
  if (runId !== undefined && !RUN_ID.test(String(runId))) return usageError('roadmap', '--run must be rl-<yyyymmdd>-<4 crockford characters>', json);
  const report = buildRoadmapReport({ cwd, runId, now, fsImpl });
  // No run record is a finding the caller acts on (exit 1), not a mistake in the call (exit 2).
  if (!report.ok) {
    if (json) console.log(JSON.stringify({ ok: false, status: 'FINDING', exitCode: 1, error: 'no-run-record', summary: report.message }, null, 2));
    else console.error(`doflow roadmap: ${report.message}`);
    return finishRuntime(1);
  }
  writeAtomic(fsImpl, report.file, report.text);
  if (json) console.log(JSON.stringify({ schema: 1, action: 'report', runId: report.runId, path: report.file, rows: report.rows }));
  else { process.stdout.write(report.text); console.log(`written: ${plain(report.file)}`); }
  return finishRuntime(0);
}

