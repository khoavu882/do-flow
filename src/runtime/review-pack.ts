const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { resolveActiveFeature } = require('./feature-resolve.ts');
const { readRegister } = require('./decision-register.ts');
const { findRunFile, readRunRecord, runStoreDir } = require('./implementation-gate.ts');
const { isNodeDone } = require('./workflow-orchestrator.ts');
const { listCheckouts } = require('./checkouts.ts');
const { projectRoot: lifecycleProjectRoot } = require('./lifecycle/root.ts');
const { readFold } = require('./lifecycle/event-store.ts');
const { verificationRunsRoot, verificationRunRecordFile } = require('./verification/engine.ts');
const { countMarkers } = require('./roadmap/facts.ts');
const { parseSeed } = require('./roadmap/rows.ts');
const { roadmapStatusResult, resolveMainRoot } = require('./roadmap/loop.ts');
const { finishRuntime, usageError } = require('./cli-result.ts');
const { isSafeSlug } = require('./task-scope.ts');

const NONE = 'none recorded';
const PACK_FILE = 'review-pack.md';
const GENERATED_NOTE = 'Generated by `doflow-run review-pack` from the records of this feature. It states what the records state and nothing else. Do not edit this file.';
const RUN_ID = /^rl-[0-9]{8}-[0-9A-Z]{4}$/;
const MARKER_FILES = ['intention/requirement.md', 'requirement.md', 'design/design.md', 'design.md', 'plan.md'];

/** One line of record text: breaks collapse and `<` is escaped, so a record cannot add a heading or open a comment. */
function oneLine(text: any): string {
  return String(text ?? '').replace(/\s*[\r\n\u2028\u2029\u0085]+\s*/g, ' ').replace(/</g, '\\<').trim();
}
const short = (sha: any): string => (typeof sha === 'string' && sha ? sha.slice(0, 8) : NONE);
const cell = (text: any): string => oneLine(text).replace(/\\/g, '\\\\').replace(/\|/g, '\\|');

function git(cwd: string, args: string[]): string | null {
  try { return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim() || null; } catch { return null; }
}

function isDir(dir: string, fsImpl: any): boolean {
  try { return fsImpl.statSync(dir).isDirectory(); } catch { return false; }
}

function readJson(file: string, fsImpl: any): any {
  try { return JSON.parse(fsImpl.readFileSync(file, 'utf8')); } catch { return null; }
}

/** The feature folder of `slug`: this checkout's, else the first other checkout of the repository that has one. */
function resolveFeature(cwd: string, slug: string): any {
  const first = resolveActiveFeature({ projectRoot: cwd, slug });
  if (!first.error) return first;
  let others: string[] = [];
  try { const found = listCheckouts({ cwd }); others = found.ok ? found.others || [] : []; } catch { /* no other checkout to ask */ }
  for (const root of others) {
    const next = resolveActiveFeature({ projectRoot: root, slug });
    if (!next.error) return next;
  }
  return first;
}

// ── facts: one object of what the records state ────────────────────────────────────────────────

function gatherResult({ cwd, slug, run, seedRow, fsImpl }: any): any {
  const branches = [`feat/${slug}`];
  const current = git(cwd, ['branch', '--show-current']);
  if (current && current.endsWith(`/${slug}`) && !branches.includes(current)) branches.push(current);
  let branch: string | null = null;
  let head: string | null = null;
  for (const candidate of branches) {
    const sha = git(cwd, ['rev-parse', '--verify', '--quiet', `refs/heads/${candidate}`]);
    if (sha) { branch = candidate; head = sha; break; }
  }
  const nodes: any[] = Array.isArray(run?.program) ? run.program : [];
  const stages = nodes.filter((n) => n?.type === 'stage');
  const lastDone = [...stages].reverse().find(isNodeDone);
  const at = Number.isInteger(run?.cursor) && run.cursor < nodes.length ? nodes[run.cursor] : null;
  return {
    taskClass: run?.taskClass ?? seedRow?.class ?? null,
    branch, head, mergeCommit: seedRow?.mergeCommit ?? null,
    runState: run?.state ?? null,
    lastStage: lastDone?.id ?? null,
    current: at ? `${at.type} ${at.id}` : null,
    progress: run ? `${nodes.filter(isNodeDone).length} of ${nodes.length} steps done` : null,
  };
}

function gatherGates({ run, register }: any): any[] {
  if (!run || !Array.isArray(run.program)) return [];
  const history: any[] = Array.isArray(run.history) ? run.history : [];
  const policyDecisions: any[] = (register?.decisions || []).filter((d: any) => d.channel === 'policy');
  return run.program.filter((n: any) => n?.type === 'gate').map((gate: any) => {
    const entry = [...history].reverse().find((h) => h?.action === 'decide-gate' && h.node === gate.id);
    if (!entry) return { id: gate.id, status: gate.status ?? 'pending' };
    const policy = entry.by === 'autopilot';
    // The inputs digest is in the register's policy entry for this gate, not in the journal.
    const registered = [...policyDecisions].reverse().find((d) => d.topic === gate.id);
    const digest = /inputs digest (sha256:[0-9a-f]+|[0-9a-f]{8,})/i.exec(registered?.rationale || '')?.[1] ?? null;
    return {
      id: gate.id, status: gate.status ?? null, decision: entry.detail ?? null, by: policy ? 'policy' : 'person', at: entry.at ?? null,
      forced: entry.forced === true, note: entry.note ?? null,
      ...(policy ? { policy: entry.policy ?? null, inputs: Array.isArray(entry.inputs) ? entry.inputs.length : null, inputsDigest: digest } : {}),
    };
  });
}

function gatherVerification({ slug, run, cwd, fsImpl }: any): any {
  const file = verificationRunRecordFile(verificationRunsRoot(cwd), run?.taskId || slug);
  let text: string;
  try { text = fsImpl.readFileSync(file, 'utf8'); } catch { return { runs: [], unreadable: 0 }; }
  const runs: any[] = [];
  let unreadable = 0;
  for (const line of text.split('\n')) {
    if (!line.trim()) continue;
    try { const r = JSON.parse(line); if (r && typeof r === 'object') runs.push(r); else unreadable += 1; } catch { unreadable += 1; }
  }
  return { runs, unreadable };
}

function gatherReview({ featureDir, fsImpl }: any): any {
  const data = readJson(path.join(featureDir, 'review', 'findings.json'), fsImpl);
  if (!data || typeof data !== 'object') return null;
  const seats: any[] = Array.isArray(data.seats) ? data.seats : [];
  const converged: any[] = Array.isArray(data.converged) ? data.converged : [];
  const seatFindings = seats.flatMap((s) => (Array.isArray(s?.findings) ? s.findings : []));
  return { data, seats, converged, seatFindings };
}

function gatherOpen({ slug, featureDir, root, run, seedRow, fsImpl }: any): any {
  let followups: any[] = [];
  let followupsUnreadable = false;
  try {
    const fold = readFold(lifecycleProjectRoot(root), { hasBody: () => false, fsImpl });
    followups = (fold.followups || []).filter((item: any) => item?.source?.feature === slug || (item?.source?.kind === 'run' && item.source.taskId === slug));
  } catch { followupsUnreadable = true; }
  const holds: any[] = [];
  const records = readRunRecords(path.join(resolveMainRoot(root), '.doflow', 'state', 'roadmap', 'runs'), fsImpl);
  const newest = [...records].reverse().find((r) => seedRow && r.rows && r.rows[seedRow.id]);
  const slot = newest?.rows?.[seedRow?.id];
  if (slot?.held) holds.push({ kind: 'held', runId: newest.runId, type: slot.held.kind ?? null, reason: slot.held.reason ?? null });
  if (slot?.paused) holds.push({ kind: 'paused', runId: newest.runId, type: null, reason: slot.paused.reason ?? null });
  if (run?.state === 'REJECTED') holds.push({ kind: 'rejected', runId: null, type: null, reason: 'the run journal records a rejected gate' });
  const markers = MARKER_FILES.map((rel) => {
    try { return { file: rel, count: countMarkers(fsImpl.readFileSync(path.join(featureDir, rel), 'utf8')) }; } catch { return null; }
  }).filter((m: any) => m && m.count > 0);
  return { followups, followupsUnreadable, holds, markers };
}

function readRunRecords(dir: string, fsImpl: any): any[] {
  let names: string[];
  try { names = fsImpl.readdirSync(dir); } catch { return []; }
  const out: any[] = [];
  for (const name of names.filter((n) => /^rl-.*\.json$/.test(n)).sort()) {
    const value = readJson(path.join(dir, name), fsImpl);
    if (value && value.schema === 1 && RUN_ID.test(value.runId) && value.rows && typeof value.rows === 'object') out.push(value);
  }
  return out.sort((a, b) => (a.createdAt < b.createdAt ? -1 : a.createdAt > b.createdAt ? 1 : a.runId < b.runId ? -1 : 1));
}

function seedRowFor(root: string, slug: string, fsImpl: any): any {
  try {
    const seed = parseSeed(fsImpl.readFileSync(path.join(resolveMainRoot(root), 'agent-docs', 'roadmap', 'rows.json'), 'utf8'));
    return seed.rows.find((r: any) => r.slug === slug) || null;
  } catch { return null; }
}

/** Everything the pack states, read once. `feature` is a `resolveFeature` result. */
function gatherFacts({ cwd, slug, feature, fsImpl = nodeFs }: any): any {
  const featureDir = feature.featureFolder;
  let register: any = null;
  let registerError: string | null = null;
  try { register = readRegister(featureDir, fsImpl); } catch (error: any) { registerError = error.message; }
  const found = findRunFile({ stateRoot: cwd, taskId: slug, slug });
  let run: any = null;
  let runError: string | null = null;
  if (found.status === 'found') {
    try { run = readRunRecord(fsImpl, found.file, runStoreDir(found.root)); } catch (error: any) { runError = error.message; }
  } else if (found.status === 'ambiguous') runError = `the run of '${slug}' is in more than one checkout`;
  const seedRow = seedRowFor(cwd, slug, fsImpl);
  const decisions: any[] = register?.decisions || [];
  return {
    slug, featureDir, run, runError, register, registerError, seedRow,
    result: gatherResult({ cwd, slug, run, seedRow, fsImpl }),
    decisions,
    gates: gatherGates({ run, register }),
    verification: gatherVerification({ slug, run, cwd, fsImpl }),
    review: gatherReview({ featureDir, fsImpl }),
    open: gatherOpen({ slug, featureDir, root: cwd, run, seedRow, fsImpl }),
  };
}

/** The counts one roadmap report row needs, taken from the same facts the pack prints. */
function countsOf(facts: any): { agent: number; autopilot: number; user: number; open: number } {
  const by = (who: string) => facts.decisions.filter((d: any) => d.decidedBy === who).length;
  const openFollowups = facts.open.followups.filter((f: any) => f.state === 'open' || f.state === 'taken').length;
  const markers = facts.open.markers.reduce((n: number, m: any) => n + m.count, 0);
  return { agent: by('agent'), autopilot: by('autopilot'), user: by('user'), open: openFollowups + facts.open.holds.length + markers };
}

// ── render ─────────────────────────────────────────────────────────────────────────────────────

function sectionResult(f: any): string[] {
  const r = f.result;
  const out = [
    `- Task class: ${r.taskClass ?? NONE}`,
    `- Branch: ${r.branch ?? NONE}`,
    `- Head commit: ${r.head ?? NONE}`,
    `- Merge commit: ${r.mergeCommit ?? NONE}`,
  ];
  if (!f.run) {
    out.push(`- Stage reached: ${NONE}`);
  } else {
    out.push(`- Run state: ${r.runState}${r.current ? `, at ${r.current}` : ''} (${r.progress})`);
    out.push(`- Stage reached: ${r.lastStage ?? 'no stage completed'}`);
  }
  return out;
}

function sectionDecisions(f: any): string[] {
  const listed = f.decisions.filter((d: any) => d.decidedBy === 'agent' || d.decidedBy === 'autopilot');
  const users = f.decisions.filter((d: any) => d.decidedBy === 'user').length;
  const out: string[] = [];
  if (listed.length === 0) out.push(`- ${NONE}`);
  for (const d of listed) {
    out.push(`- ${d.id} · ${d.stage} · ${oneLine(d.topic)} · by ${d.decidedBy}${d.status === 'live' ? '' : ` · superseded by ${d.supersededBy}`}`);
    out.push(`  - Decision: ${oneLine(d.statement)}`);
    out.push(`  - Reason: ${oneLine(d.rationale)}`);
    out.push(`  - Undo: ${d.undo ? oneLine(d.undo) : NONE}`);
  }
  out.push('', `Decisions by the user: ${users}`);
  return out;
}

function sectionGates(f: any): string[] {
  if (f.gates.length === 0) return [`- ${NONE}`];
  return f.gates.map((g: any) => {
    if (!g.by) return `- ${g.id}: ${g.status === 'pending' ? 'no decision recorded' : `status ${g.status}`}`;
    const base = `- ${g.id}: ${g.decision ?? g.status} by ${g.by}${g.forced ? ' (forced)' : ''} at ${g.at ?? NONE}`;
    if (g.by !== 'policy') return g.note ? `${base}; note: ${oneLine(g.note)}` : base;
    const policy = g.policy ? `policy ${oneLine(g.policy.id)}@${oneLine(g.policy.digest ?? NONE)}` : 'policy not recorded';
    return `${base}; ${policy}; ${g.inputs ?? NONE} inputs; inputs digest ${g.inputsDigest ?? NONE}`;
  });
}

function sectionVerification(f: any): string[] {
  const { runs, unreadable } = f.verification;
  const out: string[] = [];
  if (runs.length === 0) out.push(`- ${NONE}`);
  for (const r of runs) {
    out.push(`- ${oneLine(r.at ?? NONE)} · ${oneLine(r.verdict ?? NONE)} · risk ${oneLine(r.risk ?? NONE)} · commit ${short(r.head)} · tree ${r.clean === true ? 'clean' : r.clean === false ? 'dirty' : NONE} · report ${short(String(r.reportSha256 ?? '').replace(/^sha256:/, ''))}`);
  }
  const latest = runs[runs.length - 1];
  if (latest && f.result.head) {
    out.push('', latest.head === f.result.head
      ? `The latest run is on the head commit (${short(f.result.head)}).`
      : `The latest run is not on the head commit: it ran on ${short(latest.head)}, the head is ${short(f.result.head)}.`);
  }
  if (unreadable) out.push('', `${unreadable} verify record line(s) could not be read.`);
  return out;
}

function sectionReview(f: any): string[] {
  const r = f.review;
  if (!r) return [`- ${NONE}`];
  const sev = (list: any[], s: string) => list.filter((x) => x?.severity === s).length;
  const out = [
    `- Seats: ${r.seats.length}${r.seats.length ? ` (${r.seats.map((s: any) => oneLine(s?.id)).join(', ')})` : ''}`,
    `- Rounds: ${r.data.rounds ?? NONE}`,
    `- Reviewed head: ${r.data.reviewedHead ?? NONE}`,
    `- Seat findings: ${r.seatFindings.length} (blocker ${sev(r.seatFindings, 'blocker')}, should-fix ${sev(r.seatFindings, 'should-fix')}, note ${sev(r.seatFindings, 'note')})`,
  ];
  const status = (s: string) => r.converged.filter((x: any) => x?.status === s).length;
  out.push(`- Converged findings: ${r.converged.length} (blocker ${sev(r.converged, 'blocker')}, should-fix ${sev(r.converged, 'should-fix')}, note ${sev(r.converged, 'note')}); fixed ${status('fixed')}, refuted ${status('refuted')}, user-accepted ${status('user-accepted')}, open ${status('open')}`);
  const accepted = r.converged.filter((x: any) => x?.status === 'user-accepted');
  if (accepted.length === 0) out.push(`- Accepted without a fix: ${NONE}`);
  else {
    out.push('- Accepted without a fix:');
    for (const x of accepted) out.push(`  - ${oneLine(x.id)} · ${oneLine(x.severity)} · ${oneLine(x.locator)} · ${oneLine(x.summary)}${x.acceptedAs ? ` · ${oneLine(x.acceptedAs)}` : ''}${x.decision ? ` · ${oneLine(x.decision)}` : ''}`);
  }
  return out;
}

function sectionOpen(f: any): string[] {
  const o = f.open;
  const out: string[] = [];
  if (o.followups.length === 0) out.push(`- Follow-ups: ${NONE}`);
  else {
    out.push('- Follow-ups:');
    for (const item of o.followups) out.push(`  - ${oneLine(item.id)} · ${oneLine(item.state)} · ${oneLine(item.source?.stage ?? NONE)} · ${oneLine(item.statement)}`);
  }
  if (o.holds.length === 0) out.push(`- Holds: ${NONE}`);
  else {
    out.push('- Holds:');
    for (const h of o.holds) out.push(`  - ${h.kind}${h.type ? ` (${oneLine(h.type)})` : ''}${h.runId ? ` in ${h.runId}` : ''}: ${oneLine(h.reason ?? NONE)}`);
  }
  if (o.markers.length === 0) out.push(`- Unresolved clarification markers: ${NONE}`);
  else {
    out.push('- Unresolved clarification markers:');
    for (const m of o.markers) out.push(`  - ${m.file}: ${m.count}`);
  }
  return out;
}

function sectionNotVerified(f: any): string[] {
  const out: string[] = [];
  if (f.registerError) out.push(`- The decision register could not be read: ${oneLine(f.registerError)}`);
  else if (!f.register) out.push('- No decision register: decisions are not shown.');
  if (f.runError) out.push(`- The orchestration run could not be read: ${oneLine(f.runError)}`);
  else if (!f.run) out.push('- No orchestration run on record: task class, stage and gates are not shown.');
  if (!f.result.head) out.push(`- No branch for this feature (feat/${f.slug}) in this repository: the head commit is not shown, and verify runs cannot be compared with it.`);
  if (f.verification.runs.length === 0) out.push('- No verify run on record.');
  else out.push('- The verify record keeps the verdict, risk, commit, tree state and a digest of the report, not the commands or contract that ran.');
  if (!f.review) out.push('- No review on record (no review/findings.json).');
  if (f.open.followupsUnreadable) out.push('- The follow-up store could not be read: follow-ups are not shown.');
  if (out.length === 0) out.push(`- ${NONE}`);
  return out;
}

function renderPack(f: any, now: Date): string {
  const sections: Array<[string, string[]]> = [
    ['Result', sectionResult(f)],
    ['Decisions taken for you', sectionDecisions(f)],
    ['Gates', sectionGates(f)],
    ['Verification', sectionVerification(f)],
    ['Review', sectionReview(f)],
    ['Open items', sectionOpen(f)],
    ['Not verified', sectionNotVerified(f)],
  ];
  const out = [`# Review pack: ${f.slug}`, '', `> ${GENERATED_NOTE}`, '', `Generated at: ${now.toISOString()}`];
  sections.forEach(([title, lines], i) => out.push('', `## ${i + 1}. ${title}`, '', ...lines));
  return `${out.join('\n')}\n`;
}

function writeAtomic(fsImpl: any, file: string, content: string): void {
  fsImpl.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.tmp`;
  try {
    fsImpl.writeFileSync(tmp, content, 'utf8');
    fsImpl.renameSync(tmp, file);
  } catch (error: any) {
    try { fsImpl.rmSync(tmp, { force: true }); } catch { /* nothing to clean */ }
    throw error;
  }
}

