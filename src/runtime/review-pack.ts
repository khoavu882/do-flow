/** One line of record text: no control character or line break, `\` then `<` escaped. Every record value goes through it. */
function clean(text: any): string {
  return String(printSafe(String(text ?? ''))).replace(/\s+/g, ' ').replace(/\\/g, '\\\\').replace(/</g, '\\<').trim();
}
const cell = (text: any): string => clean(text).replace(/\|/g, '\\|');
/** Text for a terminal line (an error that echoes an argument or a path): control characters and breaks gone, nothing escaped. */
const plain = (text: any): string => String(printSafe(String(text ?? ''))).replace(/\s+/g, ' ').trim();
const short = (sha: any): string => (typeof sha === 'string' && sha ? clean(sha.slice(0, 8)) : NONE);

function git(cwd: string, args: string[]): string | null {
  try { return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim() || null; } catch { return null; }
}

function isDir(dir: string, fsImpl: any): boolean {
  try { return fsImpl.statSync(dir).isDirectory(); } catch { return false; }
}

/** `{state:'absent'}` when the file is not there, `{state:'unreadable', reason}` when it is but is not JSON or cannot be read. */
function readJsonState(file: string, fsImpl: any): any {
  let text: string;
  try { text = fsImpl.readFileSync(file, 'utf8'); } catch (error: any) {
    return error && error.code === 'ENOENT' ? { state: 'absent' } : { state: 'unreadable', reason: `${path.basename(file)}: ${error?.message ?? error}` };
  }
  try { return { state: 'ok', value: JSON.parse(text) }; } catch (error: any) {
    return { state: 'unreadable', reason: `${path.basename(file)} is not valid JSON (${error?.message ?? error})` };
  }
}

/** The feature folder of `slug`: this checkout's, else the first other checkout of the repository that has one. */
function resolveFeature(cwd: string, slug: string | null, resolve: any = resolveActiveFeature): any {
  const first = resolve({ projectRoot: cwd, slug });
  // Another checkout is asked only for a named feature: without a slug the branch of this one is the answer.
  if (!first.error || !slug) return first;
  let others: string[] = [];
  try { const found = listCheckouts({ cwd }); others = found.ok ? found.others || [] : []; } catch { /* no other checkout to ask */ }
  for (const root of others) {
    const next = resolve({ projectRoot: root, slug });
    if (!next.error) return next;
  }
  return first;
}

/** True when `dir` is a folder whose real path lies inside the real path of `root`. */
function insideRoot(dir: string, root: string, fsImpl: any): boolean {
  try {
    const rel = path.relative(fsImpl.realpathSync(root), fsImpl.realpathSync(dir));
    return rel !== '' && !rel.startsWith('..') && !path.isAbsolute(rel);
  } catch { return false; }
}

