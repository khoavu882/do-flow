'use strict';

/**
 * Decision register (IC-001 to IC-009). One `decisions/register.json` per feature folder holds
 * every decision taken during the feature's chain; `decisions.md` (live view, one row per live
 * topic) and `decisions/archive.md` (every decision with its rationale) are rendered from it and
 * never edited by hand. The register is owned by this module: no caller sets a decision's
 * `decidedBy`, `date`, `at`, `id` or `status`.
 *
 * Concurrency: every write holds the lock `task-state.js` already provides for its own files, so
 * two handoffs writing at once serialize rather than allocate the same id. Files are written with
 * a temp file and a rename; the register is written before the views, so a crash leaves a register
 * that the next write re-renders into agreement.
 */

const nodeFs = require('node:fs');
const path = require('node:path');
const { writeFileAtomic } = require('./write-file-atomic.ts');
const { acquireLock } = require('./task-state.ts');
const { resolveActiveFeature } = require('./feature-resolve.ts');
const { compactHistory } = require('./history-compactor.ts');
const { finishRuntime, usageError } = require('./cli-result.ts');

const REGISTER_VERSION = 1;
const TOPIC_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const TOPIC_MAX = 48;
const STATEMENT_MAX = 280;
const REF_RE = /^[A-Za-z]+-?[0-9]+$/;
const DEC_RE = /^DEC-[0-9]{3,}$/;
const STAGES = ['discovery', 'design', 'planning', 'implementation', 'verification', 'review'];
/** Channel -> who decided. The caller names the channel; `decidedBy` follows from it. */
const CHANNEL_DECIDED_BY: Record<string, string> = { question: 'user', gate: 'user', prompt: 'user', default: 'agent', resolution: 'agent', policy: 'autopilot' };
/** IC-005: `policy` records an evaluated gate, never a caller's claimed identity, so only the
 * in-process `orchestrate decide-gate --policy` path writes it; every caller-facing path refuses it. */
const RESERVED_CHANNEL = 'policy';
const CHANNEL_RESERVED = `channel-reserved: ${RESERVED_CHANNEL} is set only by orchestrate decide-gate --policy`;
const isReservedChannel = (channel: any): boolean => typeof channel === 'string' && channel.trim() === RESERVED_CHANNEL;
const ITEM_KEYS = ['topic', 'statement', 'channel', 'stage', 'rationale', 'supersedes', 'refs', 'source', 'undo'];
/** An unattended run adopts a default for the person to review later, so it must say how to reverse it. */
/** Matched after Unicode format characters (zero-width and the like) are removed, in any case and spacing. */
const UNATTENDED_RE = /^\s*unattended\s*:/i;
const FORMAT_CHARS = /\p{Cf}/gu;
const DECIDERS = ['user', 'agent', 'autopilot'];
/** IC-005. How a link relates a newer decision to an older one; the states a decision is in; the compaction modes. */
const LINK_KINDS = ['supersedes', 'narrows', 'reopens'] as const;
const DECISION_STATES = ['live', 'superseded', 'retired'] as const;
const COMPACT_MODES = ['history', 'closed-points'] as const;
const RETIRE_REASON_MAX = 280;
const REQUIRED_KEYS = ['topic', 'statement', 'channel', 'stage', 'rationale'];

/** Line breaks Markdown renderers and editors treat as a break, not just \r and \n. */
const LINE_BREAK = /[\r\n\u2028\u2029\u0085]/;

const GENERATED_NOTE = 'Generated from `decisions/register.json` by `doflow-run decision`. Do not edit this file.';

/** A caller mistake (exit 2). */
class DecisionUsageError extends Error {}

/** A finding the caller must act on (exit 1). */
class DecisionFinding extends Error {
  finding: string;

  constructor(finding: string, message: string) {
    super(message);
    this.finding = finding;
  }
}

// ── paths ──────────────────────────────────────────────────────────────────────────────────────

function registerFile(featureDir: string): string { return path.join(featureDir, 'decisions', 'register.json'); }
function liveViewFile(featureDir: string): string { return path.join(featureDir, 'decisions.md'); }
function archiveFile(featureDir: string): string { return path.join(featureDir, 'decisions', 'archive.md'); }

// ── register io ────────────────────────────────────────────────────────────────────────────────

function readRegister(featureDir: string, fsImpl: any = nodeFs): any {
  const file = registerFile(featureDir);
  if (!fsImpl.existsSync(file)) return null;
  let data: any;
  try {
    data = JSON.parse(fsImpl.readFileSync(file, 'utf8'));
  } catch (error: any) {
    throw new DecisionUsageError(`${file} is not valid JSON (${error.message}). The register is written atomically, so a torn file means outside interference; restore it from version control.`);
  }
  if (!data || data.version !== REGISTER_VERSION || !Array.isArray(data.decisions) || !Number.isInteger(data.nextId)) {
    throw new DecisionUsageError(`${file} is not a version ${REGISTER_VERSION} decision register; refusing to guess at its shape.`);
  }
  return data;
}

/** Writes only when the content differs, so re-rendering an unchanged view is a no-op. */
function writeIfChanged(fsImpl: any, file: string, content: string): void {
  if (fsImpl.existsSync(file) && fsImpl.readFileSync(file, 'utf8') === content) return;
  writeFileAtomic(file, content, { fsImpl });
}

function writeRegister(fsImpl: any, featureDir: string, register: any): void {
  writeFileAtomic(registerFile(featureDir), `${JSON.stringify(register, null, 2)}\n`, { fsImpl });
}

function renderViews(fsImpl: any, featureDir: string, register: any): void {
  writeIfChanged(fsImpl, liveViewFile(featureDir), renderLiveView(register));
  writeIfChanged(fsImpl, archiveFile(featureDir), renderArchive(register));
}

// ── ordering and ids ───────────────────────────────────────────────────────────────────────────

function idNumber(id: string): number { return Number(id.slice(4)); }
function formatId(n: number): string { return `DEC-${String(n).padStart(3, '0')}`; }
function byId(a: any, b: any): number { return idNumber(a.id) - idNumber(b.id); }
function byTopic(a: any, b: any): number { return a.topic < b.topic ? -1 : a.topic > b.topic ? 1 : idNumber(a.id) - idNumber(b.id); }

/** IC-005: 'superseded' when status is 'superseded'; else 'retired' when d.retired is set; else 'live'. */
function decisionState(d: any): 'live' | 'superseded' | 'retired' {
  if (d.status === 'superseded') return 'superseded';
  return d.retired ? 'retired' : 'live';
}
/** What decisions.md, the default list and stage context show. */
function inLiveView(d: any): boolean { return decisionState(d) === 'live'; }
function liveOf(register: any): any[] { return register.decisions.filter(inLiveView); }

// ── renderers ──────────────────────────────────────────────────────────────────────────────────

/** `\` is escaped first, so a statement ending in one cannot escape the pipe that closes the cell
 * (IC-007); `|` would end the cell; `<` could open an HTML comment that hides every later row. */
function cell(text: any): string { return String(text).replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/</g, '\\<'); }

/** Archive text is read by people and agents, never as HTML: `<` is escaped so `<!--` cannot hide later entries. */
function plain(text: any): string { return String(text).replace(/</g, '\\<'); }

/**
 * A one-line rationale reads inline. A longer one goes in a blockquote under the bullet, every line
 * prefixed, so no line of it can start a heading or pose as one of the entry's own bullets.
 */
function rationaleLines(rationale: any): string[] {
  const parts = plain(rationale).split(/\r\n|[\n\r\u2028\u2029\u0085]/);
  if (parts.length === 1) return [`- **Rationale:** ${parts[0]}`];
  return ['- **Rationale:**', ...parts.map((l: string) => (l === '' ? '  >' : `  > ${l}`))];
}

/** IC-007. Size depends on the number of live topics, never on how many decisions were made. */
function renderLiveView(register: any): string {
  const live = liveOf(register).sort(byTopic);
  const out = [
    `# Decisions: ${register.slug}`,
    '',
    `> ${GENERATED_NOTE} Superseded decisions and rationale are in \`decisions/archive.md\`.`,
    '',
  ];
  if (live.length === 0) {
    out.push(register.decisions.some((d: any) => d.retired) ? 'No decisions in the live view; retired ones are in `decisions/archive.md`.' : 'No live decisions yet.');
  } else {
    out.push('| ID | Topic | Decision | By | Stage | Date |', '|---|---|---|---|---|---|');
    for (const d of live) {
      out.push(`| ${d.id} | ${cell(d.topic)} | ${cell(d.statement)} | ${d.decidedBy} | ${d.stage} | ${d.date} |`);
    }
    // IC-006: a narrowed decision stays in the table; the note says it is qualified, by whom.
    const inView = new Set(live.map((d: any) => d.id));
    const narrowedBy = new Map<string, string[]>();
    for (const from of [...live].sort(byId)) {
      for (const to of from.narrows || []) {
        if (!inView.has(to)) continue;
        narrowedBy.set(to, [...(narrowedBy.get(to) || []), from.id]);
      }
    }
    if (narrowedBy.size) {
      out.push('', 'Narrowed in part:', '');
      for (const to of [...narrowedBy.keys()].sort((a, b) => idNumber(a) - idNumber(b))) out.push(`- ${to} is narrowed by ${(narrowedBy.get(to) as string[]).join(', ')}.`);
    }
  }
  return `${out.join('\n')}\n`;
}

/** IC-008. One entry per decision, by id; superseded entries stay with their rationale. */
function renderArchive(register: any): string {
  const out = [`# Decision archive: ${register.slug}`, '', `> ${GENERATED_NOTE}`];
  const sorted = [...register.decisions].sort(byId);
  for (const d of sorted) {
    out.push('', `### ${d.id}: ${d.topic}`, '');
    if (d.status === 'live') {
      out.push('- **Status:** Live');
    } else {
      const by = register.decisions.find((x: any) => x.id === d.supersededBy);
      out.push(`- **Status:** Superseded → ${d.supersededBy}${by && (by.reopens || []).includes(d.id) ? ' (reopened)' : ''}`);
    }
    if (d.retired) out.push(`- **Retired:** ${d.retired.date} · ${plain(d.retired.reason)}`);
    out.push(`- **Decision:** ${plain(d.statement)}`);
    out.push(`- **By:** ${d.decidedBy} (${d.channel}) · **Stage:** ${d.stage} · **Date:** ${d.date}`);
    if (d.supersedes.length) out.push(`- **Supersedes:** ${d.supersedes.join(', ')}`);
    if ((d.narrows || []).length) out.push(`- **Narrows:** ${d.narrows.join(', ')}`);
    if ((d.reopens || []).length) out.push(`- **Reopens:** ${d.reopens.join(', ')}`);
    const narrowers = sorted.filter((x: any) => (x.narrows || []).includes(d.id)).map((x: any) => x.id);
    if (narrowers.length) out.push(`- **Narrowed by:** ${narrowers.join(', ')}`);
    if (d.refs.length) out.push(`- **Refs:** ${d.refs.join(', ')}`);
    if (d.source) out.push(`- **Source:** ${plain(d.source)}`);
    out.push(...rationaleLines(d.rationale));
    if (d.undo) out.push(`- **Undo:** ${plain(d.undo)}`);
  }
  return `${out.join('\n')}\n`;
}

// ── item validation ────────────────────────────────────────────────────────────────────────────

function toList(value: any, what: string, label: string): string[] {
  if (value === undefined || value === null || value === '') return [];
  let list: any[];
  if (Array.isArray(value)) list = value;
  else if (typeof value === 'string') list = value.split(',');
  else throw new DecisionUsageError(`${label}: ${what} must be an array of strings`);
  const out: string[] = [];
  for (const entry of list) {
    if (typeof entry !== 'string') throw new DecisionUsageError(`${label}: ${what} must be an array of strings`);
    const trimmed = entry.trim();
    if (trimmed) out.push(trimmed);
  }
  return out;
}

/** Validates one add item against IC-003's field rules. Throws DecisionUsageError. */
function normalizeItem(raw: any, label: string): any {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) throw new DecisionUsageError(`${label}: must be an object`);
  const extra = Object.keys(raw).filter((k: string) => !ITEM_KEYS.includes(k));
  if (extra.length) {
    throw new DecisionUsageError(`${label}: unknown key${extra.length > 1 ? 's' : ''} ${extra.map((k: string) => `'${k}'`).join(', ')}. Allowed: ${ITEM_KEYS.join(', ')} (decidedBy is set by the runtime from the channel)`);
  }
  for (const key of REQUIRED_KEYS) {
    if (typeof raw[key] !== 'string' || raw[key].trim() === '') throw new DecisionUsageError(`${label}: '${key}' is required`);
  }
  const topic = raw.topic.trim();
  if (LINE_BREAK.test(topic)) throw new DecisionUsageError(`${label}: topic must be one line`);
  if (topic.length > TOPIC_MAX || !TOPIC_RE.test(topic)) {
    throw new DecisionUsageError(`${label}: topic '${topic}' must be lowercase words joined by hyphens, at most ${TOPIC_MAX} characters`);
  }
  const statement = raw.statement.trim();
  if (LINE_BREAK.test(statement)) throw new DecisionUsageError(`${label}: statement must be one line`);
  if (statement.length > STATEMENT_MAX) {
    throw new DecisionUsageError(`${label}: statement is ${statement.length} characters; the limit is ${STATEMENT_MAX}. Put the reasoning in --rationale`);
  }
  const channel = raw.channel.trim();
  if (!Object.prototype.hasOwnProperty.call(CHANNEL_DECIDED_BY, channel)) {
    throw new DecisionUsageError(`${label}: channel '${channel}' must be one of ${Object.keys(CHANNEL_DECIDED_BY).filter((c) => c !== RESERVED_CHANNEL).join(', ')}`);
  }
  const stage = raw.stage.trim();
  if (!STAGES.includes(stage)) throw new DecisionUsageError(`${label}: stage '${stage}' must be one of ${STAGES.join(', ')}`);
  const supersedes = toList(raw.supersedes, 'supersedes', label);
  for (const id of supersedes) {
    if (!DEC_RE.test(id)) throw new DecisionUsageError(`${label}: supersedes entry '${id}' is not a DEC-### id`);
  }
  if (new Set(supersedes).size !== supersedes.length) throw new DecisionUsageError(`${label}: supersedes names an id twice`);
  const refs = toList(raw.refs, 'refs', label);
  for (const ref of refs) {
    if (!REF_RE.test(ref)) throw new DecisionUsageError(`${label}: refs entry '${ref}' does not look like an id (for example FR-001)`);
  }
  let source = '';
  if (raw.source !== undefined && raw.source !== null) {
    if (typeof raw.source !== 'string' || LINE_BREAK.test(raw.source)) throw new DecisionUsageError(`${label}: source must be a one-line string`);
    source = raw.source.trim();
  }
  const rationale = raw.rationale.trim();
  let undo = '';
  if (raw.undo !== undefined && raw.undo !== null) {
    if (typeof raw.undo !== 'string' || LINE_BREAK.test(raw.undo)) throw new DecisionUsageError(`${label}: undo must be a one-line string`);
    undo = raw.undo.trim();
    if (undo.length > STATEMENT_MAX) throw new DecisionUsageError(`${label}: undo is ${undo.length} characters; the limit is ${STATEMENT_MAX}`);
  }
  if ((channel === 'default' || channel === 'resolution') && UNATTENDED_RE.test(rationale.replace(FORMAT_CHARS, '')) && !undo) {
    throw new DecisionUsageError(`${label}: a default or resolution adopted unattended (rationale starts with 'unattended:') needs 'undo': one line saying how a person reverses it`);
  }
  return { topic, statement, channel, stage, rationale, supersedes, refs, source, ...(undo ? { undo } : {}) };
}

/** Normalizes the batch (`--batch` contents) or the single item, refusing everything on one fault. */
function normalizeItems(items: any): any[] {
  if (!Array.isArray(items)) throw new DecisionUsageError('a batch must be a JSON array of decision objects');
  const normalized = items.map((raw: any, i: number) => normalizeItem(raw, `item ${i + 1}`));
  const seen = new Set();
  for (const item of normalized) {
    if (seen.has(item.topic)) throw new DecisionUsageError(`topic '${item.topic}' appears more than once in the batch; a topic takes one decision per batch`);
    seen.add(item.topic);
  }
  return normalized;
}

// ── actions ────────────────────────────────────────────────────────────────────────────────────

function summary({ action, slug, featureDir }: { action: string; slug: string; featureDir: string }): { action: string; slug: string; featureDir: string } { return { action, slug, featureDir }; }

const FOLDER_ARTIFACTS = ['intention/requirement.md', 'design/design.md', 'plan.md'];

/** IC-002. */
function initRegister({ featureDir, slug, fsImpl = nodeFs }: any): any {
  const base = summary({ action: 'init', slug, featureDir });
  if (fsImpl.existsSync(registerFile(featureDir))) return { ...base, created: false };
  const present = FOLDER_ARTIFACTS.filter((rel: string) => fsImpl.existsSync(path.join(featureDir, rel)));
  if (present.length) {
    return {
      ...base,
      created: false,
      finding: 'predates-register',
      message: `${featureDir} already holds ${present.join(', ')} and no decision register; only a folder do-brainstorm is creating gets one, so it was left unchanged`,
    };
  }
  fsImpl.mkdirSync(path.join(featureDir, 'decisions'), { recursive: true });
  const release = acquireLock(fsImpl, registerFile(featureDir));
  try {
    if (fsImpl.existsSync(registerFile(featureDir))) return { ...base, created: false };
    const register = { version: REGISTER_VERSION, slug, nextId: 1, decisions: [] };
    writeRegister(fsImpl, featureDir, register);
    renderViews(fsImpl, featureDir, register);
  } finally {
    release();
  }
  return { ...base, created: true };
}

/**
 * IC-003. All-or-nothing: the whole batch is validated and simulated against the register first,
 * and nothing is written unless every item passes.
 */
function addDecisions({ featureDir, slug, items, now = new Date(), fsImpl = nodeFs }: any): any {
  const normalized = normalizeItems(items);
  const base = summary({ action: 'add', slug, featureDir });
  if (!fsImpl.existsSync(registerFile(featureDir))) {
    return { ...base, finding: 'no-register', message: `${featureDir} has no decisions/register.json; run \`decision --action init\` when the feature is created` };
  }
  // Nothing to register: answer without taking the lock or rewriting a byte.
  if (normalized.length === 0) return { ...base, added: [], superseded: [] };
  const release = acquireLock(fsImpl, registerFile(featureDir));
  try {
    const register = readRegister(featureDir, fsImpl);
    const iso = now.toISOString();
    const added: any[] = [];
    const superseded: any[] = [];
    let conflict: any = null;
    let nextId = register.nextId;
    for (const item of normalized) {
      for (const id of item.supersedes) {
        const target = register.decisions.find((d: any) => d.id === id);
        if (!target) throw new DecisionUsageError(`topic '${item.topic}': supersedes ${id}, which is not a decision in this register`);
        if (target.status !== 'live') throw new DecisionUsageError(`topic '${item.topic}': supersedes ${id}, which is not live (it was superseded by ${target.supersededBy})`);
      }
      const unnamed = register.decisions.find((d: any) => d.status === 'live' && d.topic === item.topic && !item.supersedes.includes(d.id));
      if (unnamed && !conflict) {
        conflict = {
          finding: 'topic-conflict',
          message: unnamed.retired
            ? `topic '${item.topic}' is held by ${unnamed.id}, which is retired (in force, out of the live view); to replace it, name it in supersedes or run decision --action link --from <new id> --to ${unnamed.id} --kind supersedes. Nothing was written`
            : `topic '${item.topic}' already has live decision ${unnamed.id}; name it in supersedes to replace it. Nothing was written`,
        };
      }
      const id = formatId(nextId);
      nextId += 1;
      for (const old of item.supersedes) {
        const target = register.decisions.find((d: any) => d.id === old);
        target.status = 'superseded';
        target.supersededBy = id;
        superseded.push({ id: old, by: id });
      }
      register.decisions.push({
        id,
        topic: item.topic,
        statement: item.statement,
        decidedBy: CHANNEL_DECIDED_BY[item.channel],
        channel: item.channel,
        stage: item.stage,
        date: iso.slice(0, 10),
        at: iso,
        status: 'live',
        supersedes: item.supersedes,
        supersededBy: null,
        refs: item.refs,
        source: item.source,
        rationale: item.rationale,
        ...(item.undo ? { undo: item.undo } : {}),
      });
      added.push({ id, topic: item.topic });
    }
    if (conflict) return { ...base, ...conflict };
    register.nextId = nextId;
    writeRegister(fsImpl, featureDir, register);
    renderViews(fsImpl, featureDir, register);
    return { ...base, added, superseded };
  } finally {
    release();
  }
}

/** IC-004, IC-003 (lifecycle): `status` selects by decision state, by id; without it `all` or the live view. */
function listDecisions({ featureDir, slug, all = false, by = null, status = null, fsImpl = nodeFs }: any): any {
  const base = summary({ action: 'list', slug, featureDir });
  const register = readRegister(featureDir, fsImpl);
  if (!register) return { ...base, finding: 'no-register', message: `${featureDir} has no decisions/register.json` };
  let decisions = status
    ? register.decisions.filter((d: any) => status.includes(decisionState(d))).sort(byId)
    : all ? [...register.decisions].sort(byId) : liveOf(register).sort(byTopic);
  if (by) decisions = decisions.filter((d: any) => by.includes(d.decidedBy));
  return { ...base, decisions };
}

/** IC-005: compaction plus the view re-render, under the register lock `compactHistory` itself lacks. */
function compactDecisions({ featureDir, slug, repoRoot, paths, now = new Date(), mode = 'history', fsImpl = nodeFs }: any): any {
  const base = { ...summary({ action: 'compact', slug, featureDir }), mode };
  if (!fsImpl.existsSync(registerFile(featureDir))) {
    return { ...base, finding: 'no-register', message: `${featureDir} has no decisions/register.json; nothing was touched` };
  }
  const release = acquireLock(fsImpl, registerFile(featureDir));
  try {
    const register = readRegister(featureDir, fsImpl);
    const result = compactHistory({ repoRoot, featureDir, paths, date: now.toISOString().slice(0, 10), mode, fsImpl });
    // The views are re-rendered when anything moved, including in a partial run: the artifacts
    // that did compact are changed whatever happened to the others. Closed-points mode moves
    // artifact text only; the register, and so the views, are untouched by it.
    if (result.moved.length && mode === 'history') renderViews(fsImpl, featureDir, register);
    if (result.failed.length) {
      return {
        ...base, status: result.status, finding: 'compaction-failed',
        message: result.failed.map((f: any) => f.message).join('; '),
        artifact: result.failed[0].path, moved: result.moved, failed: result.failed,
      };
    }
    return { ...base, status: result.status, moved: result.moved, failed: [] };
  } finally {
    release();
  }
}

/** The ids a decision points at, over every link kind (IC-012). */
function linkTargets(d: any): string[] { return [...(d.supersedes || []), ...(d.narrows || []), ...(d.reopens || [])]; }

/** Shortest chain `start → … → goal` over link edges, or null (IC-012). */
function linkPath(register: any, start: string, goal: string): string[] | null {
  const byIdMap = new Map<string, any>(register.decisions.map((d: any) => [d.id, d]));
  const prev = new Map<string, string | null>([[start, null]]);
  const queue = [start];
  for (let i = 0; i < queue.length; i += 1) {
    const id = queue[i];
    if (id === goal) {
      const chain: string[] = [];
      for (let at: string | null = id; at !== null; at = prev.get(at) as string | null) chain.unshift(at);
      return chain;
    }
    for (const next of linkTargets(byIdMap.get(id) || {})) {
      if (!prev.has(next)) { prev.set(next, id); queue.push(next); }
    }
  }
  return null;
}

/**
 * IC-001. Shape checks run before the register is read; every other check runs under the register
 * lock, and nothing is written unless all pass.
 */
function linkDecisions({ featureDir, slug, from, to, kind, fsImpl = nodeFs }: any): any {
  const given: Record<string, any> = { from, to, kind };
  for (const flag of ['from', 'to', 'kind']) {
    if (typeof given[flag] !== 'string' || given[flag].trim() === '') throw new DecisionUsageError(`--${flag} is required for --action link`);
  }
  const fromId = from.trim();
  const toId = to.trim();
  const linkKind = kind.trim();
  for (const [flag, value] of [['from', fromId], ['to', toId]]) {
    if (!DEC_RE.test(value)) throw new DecisionUsageError(`--${flag} '${value}' is not a DEC-### id`);
  }
  if (!(LINK_KINDS as readonly string[]).includes(linkKind)) throw new DecisionUsageError(`--kind '${linkKind}' must be one of ${LINK_KINDS.join(', ')}`);
  if (fromId === toId) throw new DecisionUsageError(`--from and --to name the same decision ${fromId}`);
  const base = { ...summary({ action: 'link', slug, featureDir }), from: fromId, to: toId, kind: linkKind };
  if (!fsImpl.existsSync(registerFile(featureDir))) {
    return { ...summary({ action: 'link', slug, featureDir }), finding: 'no-register', message: `${featureDir} has no decisions/register.json; run \`decision --action init\` when the feature is created` };
  }
  const release = acquireLock(fsImpl, registerFile(featureDir));
  try {
    const register = readRegister(featureDir, fsImpl);
    const source = register.decisions.find((d: any) => d.id === fromId);
    const target = register.decisions.find((d: any) => d.id === toId);
    for (const [id, found] of [[fromId, source], [toId, target]]) {
      if (!found) throw new DecisionUsageError(`${id} is not a decision in this register`);
    }
    if ((source[linkKind] || []).includes(toId)) return { ...base, changed: false, superseded: [], replaced: null };
    if (target.status === 'superseded') throw new DecisionUsageError(`${toId} is not live (it was superseded by ${target.supersededBy})`);
    if (linkKind === 'narrows') {
      if (source.status === 'superseded') throw new DecisionUsageError(`--kind narrows needs a live --from; ${fromId} was superseded by ${source.supersededBy}`);
      for (const d of [source, target]) {
        if (d.retired) throw new DecisionUsageError(`--kind narrows needs both decisions in the live view; ${d.id} is retired`);
      }
    }
    const cycle = linkPath(register, toId, fromId);
    if (cycle) {
      return {
        ...summary({ action: 'link', slug, featureDir }),
        finding: 'link-cycle',
        message: `linking ${fromId} to ${toId} would close a cycle: ${cycle.join(' → ')} already exists. Nothing was written`,
        cycle,
      };
    }
    if (source.status === 'superseded') throw new DecisionUsageError(`--from ${fromId} is not live (it was superseded by ${source.supersededBy})`);
    if (source.retired) throw new DecisionUsageError(`--from ${fromId} is retired (in force, out of the live view); only a live decision can supersede or reopen another`);
    let replaced: string | null = null;
    source[linkKind] = [...(source[linkKind] || []), toId];
    const superseded: any[] = [];
    if (linkKind !== 'narrows') {
      target.status = 'superseded';
      target.supersededBy = fromId;
      superseded.push({ id: toId, by: fromId });
      if ((source.narrows || []).includes(toId)) {
        source.narrows = source.narrows.filter((id: string) => id !== toId);
        if (source.narrows.length === 0) delete source.narrows;
        replaced = 'narrows';
      }
    }
    writeRegister(fsImpl, featureDir, register);
    renderViews(fsImpl, featureDir, register);
    return { ...base, changed: true, superseded, replaced };
  } finally {
    release();
  }
}

/** IC-002. All-or-nothing: every id is checked before any is retired. */
function retireDecisions({ featureDir, slug, ids, reason, now = new Date(), fsImpl = nodeFs }: any): any {
  const list = ids === undefined || ids === null ? [] : toList(ids, 'ids', '--ids');
  if (list.length === 0) throw new DecisionUsageError('--ids is required for --action retire');
  for (const id of list) {
    if (!DEC_RE.test(id)) throw new DecisionUsageError(`--ids entry '${id}' is not a DEC-### id`);
  }
  const dup = list.find((id: string, i: number) => list.indexOf(id) !== i);
  if (dup) throw new DecisionUsageError(`--ids names ${dup} twice`);
  if (typeof reason !== 'string' || reason.trim() === '') throw new DecisionUsageError('--reason is required for --action retire: one line saying why the decision leaves the live view');
  if (LINE_BREAK.test(reason)) throw new DecisionUsageError('--reason must be one line');
  const why = reason.trim();
  if (why.length > RETIRE_REASON_MAX) throw new DecisionUsageError(`--reason is ${why.length} characters; the limit is ${RETIRE_REASON_MAX}`);
  const base = summary({ action: 'retire', slug, featureDir });
  if (!fsImpl.existsSync(registerFile(featureDir))) {
    return { ...base, finding: 'no-register', message: `${featureDir} has no decisions/register.json; run \`decision --action init\` when the feature is created` };
  }
  const release = acquireLock(fsImpl, registerFile(featureDir));
  try {
    const register = readRegister(featureDir, fsImpl);
    const found = new Map<string, any>();
    for (const id of list) {
      const d = register.decisions.find((x: any) => x.id === id);
      if (!d) throw new DecisionUsageError(`${id} is not a decision in this register`);
      found.set(id, d);
    }
    for (const id of list) {
      const d = found.get(id);
      if (d.status === 'superseded') throw new DecisionUsageError(`${id} is superseded by ${d.supersededBy}; it is already out of the live view`);
    }
    const blocking: any[] = [];
    for (const id of list) {
      const d = found.get(id);
      if (d.retired) continue;
      const stays = (other: any): boolean => Boolean(other) && other.status === 'live' && !other.retired && !list.includes(other.id);
      for (const other of [...register.decisions].sort(byId)) {
        if ((other.narrows || []).includes(id) && stays(other)) blocking.push({ id, other: other.id, direction: 'narrowed-by' });
      }
      for (const otherId of d.narrows || []) {
        if (stays(register.decisions.find((x: any) => x.id === otherId))) blocking.push({ id, other: otherId, direction: 'narrows' });
      }
    }
    if (blocking.length) {
      const pairs = blocking.map((b: any) => (b.direction === 'narrowed-by' ? `${b.id} is narrowed by ${b.other}, which stays in the live view` : `${b.id} narrows ${b.other}, which stays in the live view`));
      return {
        ...base,
        finding: 'linked-from-live',
        message: `${pairs.join('; ')}. Retire them together in one call (--ids ${blocking[0].id},${blocking[0].other}) or record a decision that supersedes one of them. Nothing was written`,
        blocking,
      };
    }
    const iso = now.toISOString();
    const retired: any[] = [];
    const unchanged: string[] = [];
    for (const id of list) {
      const d = found.get(id);
      if (d.retired) { unchanged.push(id); continue; }
      d.retired = { date: iso.slice(0, 10), at: iso, reason: why };
      retired.push({ id, topic: d.topic });
    }
    if (retired.length) {
      writeRegister(fsImpl, featureDir, register);
      renderViews(fsImpl, featureDir, register);
    }
    return { ...base, retired, unchanged };
  } finally {
    release();
  }
}

// ── verb handler ───────────────────────────────────────────────────────────────────────────────

const VALID_ACTIONS = ['init', 'add', 'list', 'compact', 'link', 'retire'];

/** `--by user,agent` → ['user', 'agent']; undefined → no filter. */
function parseBy(value: any): string[] | null {
  if (value === undefined || value === null) return null;
  const list = toList(value, 'by', '--by');
  const bad = list.filter((v: string) => !DECIDERS.includes(v));
  if (!list.length || bad.length) throw new DecisionUsageError(`--by ${bad.length ? `'${bad.join(',')}'` : 'is empty'}: valid values are ${DECIDERS.join(', ')}`);
  return list;
}

/** `--status live,retired` → ['live', 'retired']; undefined → no filter. */
function parseStatus(value: any): string[] | null {
  if (value === undefined || value === null) return null;
  const list = toList(value, 'status', '--status');
  const bad = list.filter((v: string) => !(DECISION_STATES as readonly string[]).includes(v));
  if (!list.length || bad.length) throw new DecisionUsageError(`--status ${bad.length ? `'${bad.join(',')}'` : 'is empty'}: valid values are ${DECISION_STATES.join(', ')}`);
  return list;
}

function parseMode(value: any): string {
  if (value === undefined || value === null) return 'history';
  if (!(COMPACT_MODES as readonly string[]).includes(value)) throw new DecisionUsageError(`--mode '${value}': valid values are ${COMPACT_MODES.join(', ')}`);
  return value;
}

function readBatchFile(batchPath: string, fsImpl: any): any {
  let text: string;
  try {
    // `-` is stdin, as for the evidence verb.
    text = batchPath === '-' ? fsImpl.readFileSync(0, 'utf8') : fsImpl.readFileSync(path.resolve(batchPath), 'utf8');
  } catch (error: any) {
    throw new DecisionUsageError(`cannot read --batch ${batchPath}: ${error.message}`);
  }
  try {
    return JSON.parse(text);
  } catch (error: any) {
    throw new DecisionUsageError(`--batch ${batchPath} is not valid JSON: ${error.message}`);
  }
}

/**
 * Runs one action and returns its result without printing, so other verbs (the handoff's
 * compaction) can call it directly.
 *
 * @param {Object} options
 * @param {string} options.action init | add | list | status | compact | link | retire
 * @param {string} options.projectRoot directory the feature is resolved from
 * @param {string|null} [options.slug] explicit feature override
 * @param {Object} [options.flags] add: topic, statement, channel, stage, rationale, supersedes,
 *   refs, source, undo, batch (path); list: all, by (user|agent|autopilot, comma-separated), status
 *   (live|superseded|retired, comma-separated); compact: mode (history|closed-points); link: from,
 *   to, kind (supersedes|narrows|reopens); retire: ids (comma-separated), reason
 * @returns {{exitCode:number, result?:Object, usage?:string}}
 */
function runDecision({ action = 'list', projectRoot, slug = null, flags = {}, now = new Date(), fsImpl = nodeFs }: any): { exitCode: number; result?: any; usage?: string } {
  const act = action === 'status' ? 'list' : action;
  let resolved: any = null;
  try {
    if (!VALID_ACTIONS.includes(act)) throw new DecisionUsageError(`unknown --action '${action}'. Valid: ${VALID_ACTIONS.join(', ')}`);
    if (isReservedChannel(flags.channel)) throw new DecisionUsageError(CHANNEL_RESERVED);
    const feature = resolveActiveFeature({ projectRoot, slug });
    if (feature.error) throw new DecisionUsageError(feature.message);
    resolved = { featureDir: feature.featureFolder, slug: feature.paths.feature_slug };
    let result: any;
    if (act === 'init') {
      result = initRegister({ ...resolved, fsImpl });
    } else if (act === 'list') {
      result = listDecisions({ ...resolved, all: Boolean(flags.all), by: parseBy(flags.by), status: parseStatus(flags.status), fsImpl });
    } else if (act === 'compact') {
      result = compactDecisions({ ...resolved, repoRoot: feature.featureRoot, paths: feature.paths, now, mode: parseMode(flags.mode), fsImpl });
    } else if (act === 'link') {
      result = linkDecisions({ ...resolved, from: flags.from, to: flags.to, kind: flags.kind, fsImpl });
    } else if (act === 'retire') {
      result = retireDecisions({ ...resolved, ids: flags.ids, reason: flags.reason, now, fsImpl });
    } else {
      let items: any;
      if (flags.batch) {
        const named = ITEM_KEYS.filter((k) => flags[k] !== undefined);
        if (named.length) throw new DecisionUsageError(`--batch cannot be combined with --${named[0]}`);
        items = readBatchFile(flags.batch, fsImpl);
      } else {
        const single: Record<string, any> = {};
        for (const key of ITEM_KEYS) if (flags[key] !== undefined) single[key] = flags[key];
        for (const key of REQUIRED_KEYS) {
          if (single[key] === undefined) throw new DecisionUsageError(`--${key} is required for --action add (or pass --batch <file.json>)`);
        }
        items = [single];
      }
      if (Array.isArray(items) && items.some((item: any) => isReservedChannel(item?.channel))) throw new DecisionUsageError(CHANNEL_RESERVED);
      result = addDecisions({ ...resolved, items, now, fsImpl });
    }
    return { exitCode: result.finding ? 1 : 0, result };
  } catch (error: any) {
    if (error instanceof DecisionUsageError) return { exitCode: 2, usage: error.message };
    // Another writer holds the register lock: a condition to retry, not a mistake in the call.
    if (resolved && error && /^Could not lock/.test(error.message || '')) {
      return { exitCode: 1, result: { action: act, slug: resolved.slug, featureDir: resolved.featureDir, finding: 'register-locked', message: error.message } };
    }
    throw error;
  }
}

function humanLines(result: any): string[] {
  const lines: string[] = [];
  if (result.finding) lines.push(`${result.finding}: ${result.message}`);
  if (result.action === 'init' && !result.finding) {
    lines.push(result.created ? `created ${path.join(result.featureDir, 'decisions', 'register.json')}` : 'register already exists; nothing written');
  }
  if (result.action === 'link' && !result.finding) {
    lines.push(result.changed ? `linked ${result.from} ${result.kind} ${result.to}` : `${result.from} already ${result.kind} ${result.to}; nothing written`);
  }
  if (result.action === 'retire' && !result.finding) {
    for (const r of result.retired as any[]) lines.push(`retired ${r.id} (${r.topic})`);
    for (const id of result.unchanged as string[]) lines.push(`${id} already retired; nothing written`);
  }
  for (const a of (result.added || []) as any[]) lines.push(`added ${a.id} (${a.topic})`);
  for (const s of (result.superseded || []) as any[]) lines.push(`superseded ${s.id} by ${s.by}`);
  if (result.action === 'list' && !result.finding) {
    if (result.decisions.length === 0) lines.push('No decisions.');
    for (const d of result.decisions as any[]) {
      const state = decisionState(d);
      const suffix = state === 'superseded' ? `, superseded by ${d.supersededBy}` : state === 'retired' ? ', retired' : '';
      lines.push(`${d.id}  ${d.topic}  ${d.statement}  [${d.decidedBy}, ${d.stage}${suffix}]`);
      if (d.undo) lines.push(`    undo: ${d.undo}`);
    }
  }
  if (result.action === 'compact') {
    if (result.status === 'unchanged') lines.push('nothing to compact');
    for (const m of (result.moved || []) as any[]) {
      lines.push(result.mode === 'closed-points'
        ? `moved ${m.items} closed point${m.items === 1 ? '' : 's'} (${m.lines} line${m.lines === 1 ? '' : 's'}) from ${m.path} to ${m.archive}`
        : `moved ${m.lines} line${m.lines === 1 ? '' : 's'} from ${m.path} to ${m.archive}`);
    }
  }
  return lines;
}

/**
 * `decision` verb. Exit 0 = answered, 1 = a finding the caller must act on, 2 = usage.
 * `--json` prints the result object unmodified.
 */
function handleDecisionCommand({ action = 'list', projectRoot, slug = null, flags = {}, json = false }: any = {}): number {
  const run = runDecision({ action, projectRoot: projectRoot || process.cwd(), slug, flags });
  if (run.usage !== undefined) return usageError('decision', run.usage, json);
  if (json) console.log(JSON.stringify(run.result, null, 2));
  else for (const line of humanLines(run.result)) console.log(line);
  return finishRuntime(run.exitCode);
}

