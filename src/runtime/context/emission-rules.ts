'use strict';

// Rule compiler for the hook emission table (078 IC-003, DEC-005). Run directly by Node native
// type-stripping:
//
//   node src/runtime/context/emission-rules.ts --write   rewrite the committed table
//   node src/runtime/context/emission-rules.ts --check   exit 0 equal, 1 differs, 2 usage
//
// The table is compiled from EMISSION_RULES, never written by hand: each rule's finite domain is
// enumerated through INPUT_DOMAINS and ruleAction(), so every arm the hook reads is the action
// arbitrate() gives that vector. Every combination is written as its own literal arm; a pattern
// holds no glob, so the hook's lookup matches exactly what IC-002 lists and nothing else.

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { REPO_ROOT } = require('../../helper/repo-root.ts');
const { EMISSION_RULES, INPUT_DOMAINS, ruleAction } = require('./arbitrate.ts');

const TABLE_REL = 'core/harnesses/shared/hooks/policies/emission-rules.sh';
const RULES_VERSION = 1;
const MAX_BYTES_DEFAULT = 16384;
const SUMMARY_CAP = 4000;
const SUMMARY_READ = 65536;

/** Every value combination of the named inputs, in vector order. */
function combinations(inputs: readonly string[]): string[][] {
  let out: string[][] = [[]];
  for (const name of inputs) {
    const domain: readonly string[] = INPUT_DOMAINS[name];
    out = out.flatMap((prefix) => domain.map((value) => [...prefix, value]));
  }
  return out;
}

/** JSON with object keys sorted at every depth, so the digest does not depend on key order. */
function canonicalJson(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  if (value && typeof value === 'object') {
    const entries = Object.keys(value as object).sort()
      .map((key) => `${JSON.stringify(key)}:${canonicalJson((value as Record<string, unknown>)[key])}`);
    return `{${entries.join(',')}}`;
  }
  return JSON.stringify(value);
}

function rulesDigest(rules: readonly unknown[]): string {
  return crypto.createHash('sha256').update(canonicalJson(rules), 'utf8').digest('hex');
}

function compare(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

interface CompiledArm { event: string; segment: string; vector: string; action: string }

/** Every non-skip combination of every rule, sorted by event, segment, vector. */
function compileArms(rules: readonly any[] = EMISSION_RULES): CompiledArm[] {
  const arms: CompiledArm[] = [];
  for (const r of rules) {
    for (const values of combinations(r.inputs)) {
      const action = ruleAction(r, values);
      if (action !== 'skip') arms.push({ event: r.event, segment: r.segment, vector: values.join(':'), action });
    }
  }
  return arms.sort((a, b) => compare(a.event, b.event) || compare(a.segment, b.segment) || compare(a.vector, b.vector));
}

/** A value safe inside a single-quoted bash pattern, with no glob character. */
function literal(text: string): string {
  if (!/^[A-Za-z0-9._:|-]+$/.test(text)) throw new TypeError(`emission-rules: ${JSON.stringify(text)} is not a plain token`);
  return text;
}

/** IC-003: the full text of `emission-rules.sh`. */
function compileEmissionTable(rules: readonly any[] = EMISSION_RULES): string {
  const lines = [
    '# Generated by node src/runtime/context/emission-rules.ts --write. Do not edit.',
    `# rules-digest: sha256:${rulesDigest(rules)}`,
    `DF_RULES_VERSION=${RULES_VERSION}`,
    `DF_RULES_MAX_BYTES_DEFAULT=${MAX_BYTES_DEFAULT}`,
    `DF_RULES_SUMMARY_CAP=${SUMMARY_CAP}`,
    `DF_RULES_SUMMARY_READ=${SUMMARY_READ}`,
    'doflow_emission_rule() {',
    "  # $1 = event.segment, $2 = vector: input values joined with ':' in IC-002 order",
    '  case "$1|$2" in',
  ];
  for (const arm of compileArms(rules)) {
    lines.push(`    '${literal(`${arm.event}.${arm.segment}|${arm.vector}`)}') DF_ACTION=${literal(arm.action)} ;;`);
  }
  lines.push('    *) DF_ACTION=skip ;;', '  esac', '}');
  return `${lines.join('\n')}\n`;
}

const USAGE = 'usage: node src/runtime/context/emission-rules.ts --write|--check\n';

/** The CLI: 0 written or equal, 1 the committed table differs from the rules, 2 usage. */
function main(argv: string[]): number {
  if (argv.length !== 1 || (argv[0] !== '--write' && argv[0] !== '--check')) {
    process.stderr.write(USAGE);
    return 2;
  }
  const target = path.join(REPO_ROOT, TABLE_REL);
  const expected = compileEmissionTable();
  if (argv[0] === '--write') {
    fs.writeFileSync(target, expected);
    return 0;
  }
  let actual: string | null;
  try { actual = fs.readFileSync(target, 'utf8'); } catch { actual = null; }
  if (actual === expected) return 0;
  process.stderr.write(`emission-rules: ${TABLE_REL} is ${actual === null ? 'missing' : 'stale'}; run node src/runtime/context/emission-rules.ts --write\n`);
  return 1;
}

module.exports = { TABLE_REL, canonicalJson, compileArms, compileEmissionTable, rulesDigest };

if (require.main === module) process.exitCode = main(process.argv.slice(2));
