'use strict';

// DESIGN.md generator (feature 133). console/DESIGN.md is the agent-readable design file of the Console.
// Its prose is hand-written; two blocks are generated from the shipped CSS so they cannot drift:
//
//   <!-- generated:tokens -->      every custom property of web/tokens.css (value, or light | dark)
//   <!-- generated:components -->  the top-level class blocks of web/app.css (BEM block names, sorted)
//   <!-- /generated -->            closes either block
//
//   node console/scripts/build-design-md.ts            check: exit 1 when DESIGN.md differs from what would be generated
//   node console/scripts/build-design-md.ts --write    rewrite the generated blocks in place
//
// design-md.test.ts uses the pure functions below (parseTokens, tokensBlock, componentsBlock, render, check).
// Dev only: console/DESIGN.md and console/scripts/ are not in the package's `files`.

const fs = require('node:fs');
const path = require('node:path');

const CONSOLE_ROOT = path.join(__dirname, '..');
const SCRIPT_FILE = __filename;
const DESIGN_FILE = path.join(CONSOLE_ROOT, 'DESIGN.md');
const TOKENS_FILE = path.join(CONSOLE_ROOT, 'web', 'tokens.css');
const APP_FILE = path.join(CONSOLE_ROOT, 'web', 'app.css');

const CLOSE = '<!-- /generated -->';
const NOTE = '<!-- Generated by console/scripts/build-design-md.ts from the CSS. Change the CSS, then run it with --write. -->';

type Rule = { at: string | null, selector: string, decls: Array<[string, string]> };
type Tokens = { invariant: Array<[string, string]>, themed: Array<[string, string, string]>, overrides: Array<[string, string, string]> };

const DARK_MEDIA = '@media (prefers-color-scheme: dark)';

const stripComments = (css: string): string => css.replace(/\/\*[\s\S]*?\*\//g, '');

/** Every style rule with the at-rule prelude wrapping it (null at top level); only custom properties are kept. */
function parseRules(css: string): Rule[] {
  const rules: Rule[] = [];
  const walk = (source: string, at: string | null) => {
    let index = 0;
    while (index < source.length) {
      const open = source.indexOf('{', index);
      if (open === -1) break;
      const prelude = source.slice(index, open).trim();
      let depth = 1;
      let close = open + 1;
      while (close < source.length && depth > 0) {
        if (source[close] === '{') depth += 1;
        else if (source[close] === '}') depth -= 1;
        close += 1;
      }
      const body = source.slice(open + 1, close - 1);
      if (prelude.startsWith('@')) walk(body, prelude);
      else {
        const decls: Array<[string, string]> = [];
        for (const part of body.split(';')) {
          const colon = part.indexOf(':');
          if (colon === -1) continue;
          const name = part.slice(0, colon).trim();
          if (name.startsWith('--')) decls.push([name, part.slice(colon + 1).trim()]);
        }
        rules.push({ at, selector: prelude, decls });
      }
      index = close;
    }
  };
  walk(stripComments(css), null);
  return rules;
}

/** Tokens of tokens.css: the theme-invariant ones, the themed ones (light, dark) and the per-media overrides. */
function parseTokens(tokensCss: string): Tokens {
  const rules = parseRules(tokensCss);
  const root = rules.find((rule) => rule.at === null && rule.selector === ':root');
  const dark = rules.find((rule) => rule.at === null && rule.selector === '[data-theme="dark"]');
  if (!root || !dark) throw new Error('build-design-md: tokens.css needs a :root block and a [data-theme="dark"] block');
  const darkValues = new Map(dark.decls);
  const rootNames = new Set(root.decls.map(([name]) => name));
  const invariant: Array<[string, string]> = [];
  const themed: Array<[string, string, string]> = [];
  for (const [name, value] of root.decls) {
    const night = darkValues.get(name);
    if (night === undefined) invariant.push([name, value]);
    else themed.push([name, value, night]);
  }
  for (const [name, value] of dark.decls) if (!rootNames.has(name)) themed.push([name, '(none)', value]);
  // The prefers-color-scheme dark block repeats the dark block (tokens.test.ts proves it), so it is not listed twice.
  const overrides: Array<[string, string, string]> = [];
  for (const rule of rules) {
    if (rule.at === null || (rule.at === DARK_MEDIA && rule.selector === ':root:not([data-theme="light"])')) continue;
    for (const [name, value] of rule.decls) overrides.push([rule.at, name, value]);
  }
  return { invariant, themed, overrides };
}

/** The generated token list: one `--name: value` line per token, light | dark for themed tokens. */
function tokensBlock(tokensCss: string): string {
  const { invariant, themed, overrides } = parseTokens(tokensCss);
  const lines = ['```text', '# theme-invariant (:root)'];
  for (const [name, value] of invariant) lines.push(`${name}: ${value}`);
  lines.push('# themed: light | dark ([data-theme="dark"], also under prefers-color-scheme: dark unless data-theme is light)');
  for (const [name, light, night] of themed) lines.push(`${name}: ${light} | ${night}`);
  lines.push('# overrides (:root inside the media query)');
  for (const [at, name, value] of overrides) lines.push(`${at} ${name}: ${value}`);
  lines.push('```');
  return lines.join('\n');
}

/** Every class name in a stylesheet: comments, strings and url() removed first, so only selectors (and values like .5) are left. */
function classNames(css: string): string[] {
  const text = stripComments(css).replace(/"[^"]*"|'[^']*'/g, '""').replace(/url\([^)]*\)/g, '');
  const found = new Set<string>();
  for (const match of text.matchAll(/(?<![\w-])\.([a-z][a-z0-9]*(?:-[a-z0-9]+)*(?:__[a-z0-9]+(?:-[a-z0-9]+)*)?(?:--[a-z0-9]+(?:-[a-z0-9]+)*)?)/g)) found.add(match[1]);
  return [...found].sort();
}

/** The top-level BEM blocks: the name before the first `__` or `--`, de-duplicated and sorted; state hooks (is-, has-) are not components. */
function componentBlocks(appCss: string): string[] {
  const blocks = new Set<string>();
  for (const name of classNames(appCss)) {
    const block = name.split('__')[0].split('--')[0];
    if (/^(is|has)-/.test(block)) continue;
    blocks.add(block);
  }
  return [...blocks].sort();
}

/** The generated component list: the class blocks of app.css, wrapped to short lines. */
function componentsBlock(appCss: string): string {
  const lines: string[] = [];
  let line = '';
  for (const block of componentBlocks(appCss)) {
    const item = `\`.${block}\``;
    if (line !== '' && line.length + item.length + 2 > 100) { lines.push(line); line = ''; }
    line = line === '' ? item : `${line}, ${item}`;
  }
  if (line !== '') lines.push(line);
  return lines.join('\n');
}

function replaceBlock(text: string, name: string, body: string): string {
  const open = `<!-- generated:${name} -->`;
  const start = text.indexOf(open);
  if (start === -1) throw new Error(`build-design-md: DESIGN.md has no ${open} marker`);
  const end = text.indexOf(CLOSE, start);
  if (end === -1) throw new Error(`build-design-md: the ${open} block is not closed by ${CLOSE}`);
  return `${text.slice(0, start)}${open}\n${NOTE}\n${body}\n${text.slice(end)}`;
}

/** DESIGN.md text with both generated blocks rewritten from the CSS; the prose is untouched. */
function render(existingText: string, tokensCss: string, appCss: string): string {
  return replaceBlock(replaceBlock(existingText, 'tokens', tokensBlock(tokensCss)), 'components', componentsBlock(appCss));
}

/** The text of DESIGN.md with every generated block removed: the hand-written prose only. */
function proseOf(text: string): string {
  return text.replace(/<!-- generated:[a-z]+ -->[\s\S]*?<!-- \/generated -->/g, '');
}

/** `ok` is false when DESIGN.md differs from what render() would write; `expected` is that text. */
function check(designText: string, tokensCss: string, appCss: string): { ok: boolean, expected: string } {
  const expected = render(designText, tokensCss, appCss);
  return { ok: expected === designText, expected };
}

function main(argv: readonly string[]): number {
  const write = argv.includes('--write');
  if (argv.some((arg) => arg !== '--write')) { console.error('usage: build-design-md.ts [--write]'); return 2; }
  const tokensCss = fs.readFileSync(TOKENS_FILE, 'utf8');
  const appCss = fs.readFileSync(APP_FILE, 'utf8');
  const current = fs.readFileSync(DESIGN_FILE, 'utf8');
  const { ok, expected } = check(current, tokensCss, appCss);
  if (write) {
    if (!ok) fs.writeFileSync(DESIGN_FILE, expected);
    console.log(ok ? 'DESIGN.md is up to date' : 'DESIGN.md generated blocks rewritten');
    return 0;
  }
  if (!ok) { console.error('console/DESIGN.md differs from web/tokens.css and web/app.css. Run: node console/scripts/build-design-md.ts --write'); return 1; }
  console.log('DESIGN.md matches the CSS');
  return 0;
}

if (require.main === module) {
  try {
    process.exit(main(process.argv.slice(2)));
  } catch (error) {
    console.error((error as Error).message);
    process.exit(1);
  }
}

module.exports = { SCRIPT_FILE, DESIGN_FILE, TOKENS_FILE, APP_FILE, parseRules, parseTokens, tokensBlock, classNames, componentBlocks, componentsBlock, render, proseOf, check };
